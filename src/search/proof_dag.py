# ---------- Theory abduction (deferred: assume → cover → gate → prove) -------
# Middle ground between eager abduction (lemmas must arrive WITH proofs,
# one gated compile) and full deferral (assume everything, prove later):
#   1. INVENT freely — the model proposes a THEORY: lemma STATEMENTS
#      only (no proofs yet) plus optional new definitions/abstractions,
#      with NO caps on count, length, or novelty, plus a tactic per
#      stuck leaf that uses the theory.
#   2. Minimal covering set — statements not needed to satisfy the
#      leaves are greedily dropped.
#   3. SATISFACTION GATE FIRST — with the statements assumed (sorry-
#      stubbed, probe compile only, NEVER counted as a solve), every
#      stuck leaf must close. Failures feed back into a revision.
#   4. Only then PROVE the theory — each lemma proved separately
#      (kernel-gated, sorry-free); a failed lemma proof feeds its
#      errors into a REVISED theory, which must re-pass the gate.
#   5. Commit — proved declarations spliced into the header, leaf
#      tactics applied, control returns to the normal verify loop.
# Soundness: sorry appears only in probe compiles that gate
# satisfaction; the final accepted proof still goes through the
# caller's fresh-compile oracle untouched.

