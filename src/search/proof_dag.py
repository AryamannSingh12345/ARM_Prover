"""Sketch-guided proof-DAG decomposition.

The thesis: hard theorems fail under whole-proof generation because the
LLM cannot plan a 10+ tactic sequence in one shot, and fail under
step-search because there is no high-level plan. A proof-DAG sits
between: the LLM emits a TYPED graph of intermediate `have` claims that
together discharge the goal, each leaf is closed by a (much cheaper)
local closer tactic, and the assembly is verified end-to-end in a fresh
Lean session.

The sketch is generated by an LLM call, parsed as strict JSON, turned
into a single `theorem … := by have h₁ : … := by … ; … ; <closer>`
block, and handed to `verify_proof`. Failures classify whether the
sketch parsed, whether assembly produced syntactically valid Lean, and
what Lean reported when verifying.

V2 adds TARGETED LEAF REPAIR: assembly tracks which body lines belong
to which `have`; on a verify failure, Lean's per-line errors are
attributed to individual leaves and only the broken leaves are
regenerated (with their errors fed back) — verified leaves are kept.
This is the property that distinguishes the DAG from whole-proof
pass@k, where any error discards the entire sample.

OUTPUT CONTRACT (sketch JSON the LLM must emit)
================================================

    {
      "haves": [
        {
          "id":     "h_aux1",
          "type":   "<Lean 4 Prop, e.g. 0 ≤ a + b>",
          "tactic": "<single Lean tactic line that closes this have>",
          "depends": ["h_aux0", ...]    // optional, ids of other haves
        },
        ...
      ],
      "closer": "<final tactic body that closes the original goal,
                  using both the theorem's own hypotheses and the
                  introduced haves by name>"
    }

ASSEMBLY
========

    theorem T (… hyps …) : G := by
      have h_aux1 : <type1> := by <tactic1>
      have h_aux2 : <type2> := by <tactic2>
      ...
      <closer>

The `haves` are emitted in topological order (a `have` referencing
`h_aux_k` must appear after `h_aux_k`). The parser sorts by `depends`
to enforce this. Cycles → reject sketch.

CLEAN-EVAL
==========

The sketch LLM sees the theorem STATEMENT (no proof tactics). Same
"weaker leak" as any LLM-normalised header — the model could recall the
problem from training data, but it cannot leak from the search-time
proof corpus. Callers should record `dag_used=true` in JSONL.
"""
