def _parse_theory(raw: str):
    """Parse the theory JSON → ((defs, lemmas, leaf_tactics), error).

    `lemmas` = [(name, statement)] with any accidental `:= proof` tail
    truncated; statements must look like lemma/theorem headers. Defs
    and tactics are forbidden-tactic-scanned (they are final code);
    lemma statements are not (WE stub them with sorry for the probe)."""
    obj = _extract_json_object(raw)
    if not isinstance(obj, dict):
        return None, "theory_no_json_object"
    defs_raw = obj.get("defs") or []
    lemmas_raw = obj.get("lemmas") or []
    tactics_raw = obj.get("leaf_tactics") or {}
    if not isinstance(lemmas_raw, list) or not isinstance(tactics_raw, dict):
        return None, "theory_bad_shape"
    defs: list[str] = []
    for d in (defs_raw if isinstance(defs_raw, list) else []):
        d = str(d or "").strip()
        if not d:
            continue
        if _FORBIDDEN_TAC_RE.search(d):
            return None, "theory_def_forbidden"
        # Environment integrity. A silent `continue` is NOT enough here:
        # the whole theory must be refused and the reason fed back, so a
        # model cannot keep probing for a splice that changes the goal.
        _why = _decl_safety.unsafe_declaration(d)
        if _why:
            return None, f"theory_def_unsafe: {_why}"
        if not _DEF_DECL_RE.match(d):
            continue
        defs.append(d)
    lemmas: list[tuple[str, str]] = []
    for lem in lemmas_raw:
        if not isinstance(lem, dict):
            continue
        name = str(lem.get("name") or "").strip()
        stmt = str(lem.get("statement") or "").strip()
        if not stmt:
            continue
        cut = stmt.find(":=")
        if cut >= 0:
            stmt = stmt[:cut].rstrip()
        if not _LEMMA_DECL_RE.match(stmt):
            continue
        lemmas.append((name or f"aux_{len(lemmas)}", stmt))
    tactics: dict[str, str] = {}
    for k, v in tactics_raw.items():
        v = _strip_leading_by(str(v or ""))
        if not v:
            continue
        if _FORBIDDEN_TAC_RE.search(v):
            return None, "theory_tactic_forbidden"
        tactics[str(k)] = v
    if not lemmas and not defs:
        return None, "theory_empty"
    if not tactics:
        return None, "theory_no_leaf_tactics"
    return (defs, lemmas, tactics), None


def _own_decl_name(header: str) -> str:
    """The name of the theorem the header declares, or ""."""
    m = re.match(r"\s*(?:private\s+|protected\s+|noncomputable\s+)*"
                 r"(?:theorem|lemma)\s+([A-Za-z_][A-Za-z0-9_'!?₀-₉]*)",
                 header[_decl_offset(header):])
    return m.group(1) if m else ""


def references_own_name(header: str, body: str) -> str | None:
    """The theorem's own name if the PROOF BODY cites it, else None.

    A proof that mentions the theorem it is proving makes Lean elaborate
    the declaration as RECURSIVE, and it fails with "fail to show
    termination / failed to infer structural recursion". That is a HEADER
    error, which aborts the whole attempt by design — error attribution
    after a broken header is unreliable. So one stray self-citation
    throws away the run.

    Observed repeatedly on p1967a2_v1 (sketches 2 and 3, both killed this
    way at t=931s and t=2747s).

    The boundary check deliberately excludes a trailing `_`, so the
    companion `putnam_1967_a2_solution` — which bodies legitimately cite
    — does NOT match the theorem name `putnam_1967_a2`.

    It also excludes a LEADING `.`, so a field access `h.putnam_1967_a2`
    is not flagged. That exclusion had a hole: `_root_.putnam_1967_a2` is
    dotted too, but it is a genuine self-citation — the `_root_.` prefix
    is exactly how one names the top-level declaration. So it is matched
    explicitly, ahead of the boundary rule.

    Observed on p1967a2_v4 (2026-08-12): at t=10538s the closer emitted
    `_root_.putnam_1967_a2`, slipped past this guard, and reached Lean —
    which reported `Unknown identifier` only because the theorem is not
    yet in scope during its own elaboration. The same run was later
    stopped correctly at t=11508s by the bare-name rule, which is what
    the hole had been hiding.
    """
    nm = _own_decl_name(header)
    if not nm:
        return None
    pat = (rf"_root_\.{re.escape(nm)}(?![A-Za-z0-9_'])"
           rf"|(?<![A-Za-z0-9_.']){re.escape(nm)}(?![A-Za-z0-9_'])")
    return nm if re.search(pat, body or "") else None


def _is_timeout_error(errs: str) -> bool:
    """Did the verifier run out of time rather than find a fault?

    The distinction matters wherever error text is ATTRIBUTED: a timeout
    carries no `file:line:col:` markers, so any logic that decides "which
    part is to blame" sees nothing to blame and can silently conclude
    nothing is wrong.
    """
    e = (errs or "").strip().lower()
    return e.startswith("timeout") or "timeout after" in e


def _norm_ws(s: str) -> str:
    return re.sub(r"\s+", "", s)


def _normalize_proof_indent(proof: str) -> str:
    """Fix the misparse-in-waiting where a model emits

        have hd : P := by linarith
         rw [...]
         nlinarith [...]

    — continuation lines uniformly indented DEEPER than a first line
    whose inline `by <tac>` is already complete. Assembled under
    `:= by`, Lean attaches those lines to the inner `by` block: the
    outer proof ends after line 1 (unsolved goals) and the rest falls
    out as top-level garbage (killed arm_engel3_final1). When the
    first line does NOT end in a bare `by`, dedent the continuation
    lines by their common indent so they sit at the first line's
    level. Genuine sub-blocks (first line ending in bare `by`, or
    mixed-depth continuations reaching column 0) are left alone."""
    lines = proof.splitlines()
    if len(lines) < 2:
        return proof
    first, rest = lines[0], lines[1:]
    if len(first) != len(first.lstrip()):
        return proof  # first line itself indented — structure unknown
    indents = [len(ln) - len(ln.lstrip()) for ln in rest if ln.strip()]
    if not indents or min(indents) == 0:
        return proof
    if first.rstrip().endswith("by"):
        return proof  # continuation genuinely belongs to that by-block
    m = min(indents)
    return "\n".join(
        [first, *(ln[m:] if ln.strip() else ln for ln in rest)])


def _strip_leading_by(tactic: str) -> str:
    """Normalize a model-emitted tactic block that begins with `by`.

    Every assembly site already supplies the `:= by` (or is itself in
    tactic position), so a leading `by` produces `by by` — a parse
    error that killed two mathematically-correct lemma proofs on
    arm_engel3_v2. Dedents the remainder so relative indentation
    survives."""
    s = (tactic or "").strip()
    if s == "by":
        return ""
    if s.startswith("by\n") or s.startswith("by "):
        s = s[2:].lstrip("\n")
        import textwrap
        s = textwrap.dedent(s).strip("\n")
    return s


#: Normalisation tactics whose FAILURE almost always means "nothing left
#: to do" rather than "the proof is wrong". In Lean 4 a no-op `simp` is a
#: hard ERROR, so one of these landing on an already-normalised goal
#: aborts an otherwise-correct proof.
_NOOP_PRONE_TACTICS = (
    "simp_all", "simp", "norm_num", "ring_nf", "push_cast",
    "field_simp", "dsimp", "norm_cast",
)
_NOOP_PRONE_RE = re.compile(
    r"^(?P<indent>\s*)(?P<tac>(?:" + "|".join(_NOOP_PRONE_TACTICS) + r")\b.*)$")

#: Appended after a submitted block. `all_goals` succeeds vacuously when
#: no goals remain, and every member is `try`, so on a proof that already
#: closes everything this is a no-op.
_RESIDUAL_SWEEP = (
    "all_goals try omega",
    "all_goals try ring",
    "all_goals try simp_all",
    "all_goals try ac_rfl",
)


def harden_tactic_block(proof_text: str, sweep: bool = True) -> str:
    """Make a model-submitted tactic block robust to two failure modes
    that cost this project more lemmas than any mathematical difficulty.

    MEASURED on the p1967b5 run (15.3 h, 64 compiles): 9 of 13 lost
    lemma attempts — 69% — died of one of these, including the crux
    lemma three separate times.

      1. `simp made no progress`, a hard error in Lean 4, when a
         normalisation tactic lands on an already-normalised goal
         (3 lemmas lost). Fixed by wrapping such tactics in `try`.
      2. A trivial residual goal left unclosed — `1 + (1 + A) = 2 + A`,
         `∑ … + 1 = 1 + ∑ …` — because the model writes proofs blind and
         mispredicts which subgoals survive (6 lemmas lost). Fixed by
         sweeping leftover goals.

    SAFETY: this cannot break a proof that currently compiles. `try t`
    is definitionally `t` whenever `t` succeeds, and `all_goals try …`
    is vacuous when no goals remain. It only ever adds behaviour on a
    path that was already failing.

    `|` means two different things in Lean and they must be told apart:

      `first | simp | ring`          ALTERNATION — `simp` FAILING is how
                                     control reaches `ring`. Wrapping it
                                     in `try` would silently make the
                                     alternation always take branch one.
      `induction m with | succ n ih =>`
                                     CASE MARKER — its body is ordinary
                                     tactics, safe to harden. This is
                                     where b5's `simp` failures actually
                                     lived, so treating it as alternation
                                     would miss the failures this exists
                                     for.

    The discriminator is `=>`: a `|` line carrying one opens a case, a
    `|` line without one is an alternation branch. Alternation branches,
    `<;>` chains and anything following a bare `first` are left alone.
    """
    lines = (proof_text or "").split("\n")
    out: list[str] = []
    prev_is_alt = False
    for raw in lines:
        stripped = raw.strip()
        is_case_marker = stripped.startswith("|") and "=>" in stripped
        is_alt_branch = stripped.startswith("|") and "=>" not in stripped
        alt_context = (
            prev_is_alt
            or is_alt_branch
            or "<;>" in raw
            or ("|" in raw and not is_case_marker)
        )
        m = _NOOP_PRONE_RE.match(raw)
        if m and not alt_context:
            out.append(f"{m.group('indent')}try {m.group('tac')}")
        else:
            out.append(raw)
        # A case marker does NOT put its body in alternation context.
        prev_is_alt = stripped.endswith("first") or is_alt_branch

    if sweep:
        base = ""
        for raw in lines:
            if raw.strip():
                base = raw[: len(raw) - len(raw.lstrip())]
                break
        out.extend(f"{base}{s}" for s in _RESIDUAL_SWEEP)
    return "\n".join(out)


def combine_candidates(tactics: list[str]) -> str:
    """Combine candidate tactic blocks into one `first | (…) | (…)` so a
    single compile tries them in order. Dedupes on the inlined form.
    One candidate passes through verbatim (multi-line stays multi-line).
    Structure-sensitive candidates (calc / bullets / match) can't be
    inlined into `first` alternatives — they're skipped when combining,
    but a lone structure-sensitive candidate passes through verbatim."""
    seen: set[str] = set()
    inlined: list[str] = []
    kept: list[str] = []
    for t in tactics:
        if not _inlinable(t):
            continue
        one = _inline_tactic_body(t)
        if not one or one in seen:
            continue
        seen.add(one)
        inlined.append(one)
        kept.append(t)
    if not inlined:
        # All candidates were structure-sensitive — use the first
        # non-empty one as-is rather than returning nothing.
        for t in tactics:
            if t.strip():
                return t
        return ""
    if len(inlined) == 1:
        return kept[0]
    return "first | " + " | ".join(f"({s})" for s in inlined)


