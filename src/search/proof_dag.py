def _apply_repairs(
    sketch: Sketch,
    raw: str,
    broken_ids: set[str],
    closer_broken: bool,
    setup_broken: bool = False,
) -> tuple[list[str], str | None]:
    """Parse a repair response and apply it to `sketch` in place.

    Only ids that were actually flagged broken are repairable — the LLM
    rewriting a verified leaf would silently discard confirmed work.
    Returns (applied_ids, error_or_None).
    """
    obj = _extract_json_object(raw)
    if obj is None or not isinstance(obj, dict):
        return [], "repair_no_json_object"
    applied: list[str] = []
    by_id = {h.id: h for h in sketch.haves}
    repairs = obj.get("repairs") or []
    if not isinstance(repairs, list):
        return [], "repairs_not_list"
    for r in repairs:
        if not isinstance(r, dict):
            continue
        rid = r.get("id")
        if not isinstance(rid, str) or rid not in broken_ids or rid not in by_id:
            continue
        rtype = r.get("type")
        rtac = r.get("tactic")
        if not isinstance(rtac, str) or not rtac.strip():
            continue
        if _FORBIDDEN_TAC_RE.search(rtac):
            continue
        node = by_id[rid]
        if isinstance(rtype, str) and rtype.strip():
            node.type_text = rtype.strip()
        node.tactic = rtac.strip()
        applied.append(rid)
    new_closer = obj.get("closer")
    if (closer_broken and isinstance(new_closer, str) and new_closer.strip()
            and not _FORBIDDEN_TAC_RE.search(new_closer)):
        sketch.closer = new_closer.strip()
        applied.append(CLOSER_ID)
    # Setup replacement — only when the setup block was flagged broken
    # (same gating principle as the closer: never let the model rewrite
    # a part that verified). Accepts a list of lines or one string.
    new_setup = obj.get("setup")
    if setup_broken and new_setup is not None:
        if isinstance(new_setup, str):
            new_setup = new_setup.splitlines()
        if isinstance(new_setup, list):
            lines = [str(x).strip() for x in new_setup
                     if str(x or "").strip()]
            if lines and not any(
                    _FORBIDDEN_TAC_RE.search(x) for x in lines):
                sketch.setup = lines
                applied.append(SETUP_ID)
    if not applied:
        return [], "repair_applied_nothing"
    return applied, None


