def insert_lemmas_before_decl(header: str, lemmas_lean: str) -> str:
    """Splice verified lemma declarations into a header, after the
    prelude (opens/set_options/earlier decls) and before the final
    declaration — the same position the hand-seeded files use."""
    off = _decl_offset(header)
    return header[:off] + lemmas_lean.rstrip() + "\n\n" + header[off:]


#: Top-level declaration heads, for reading what a source puts IN SCOPE.
#: Kept separate from `_LAST_DECL_RE` (which finds the FINAL declaration
#: only) and from `_DEF_DECL_RE` / `_LEMMA_DECL_RE` (which validate ONE
#: candidate declaration): this one enumerates EVERY declaration in a
#: multi-declaration source.
_SCOPE_DECL_RE = re.compile(
    r"(?m)^[ \t]*(?:@\[[^\]]*\][ \t\r\n]*)*"
    r"(?:noncomputable[ \t]+|private[ \t]+|protected[ \t]+)*"
    r"(?P<kind>theorem|lemma|def|abbrev|structure|inductive|instance)\b")


def _signature_of(block: str) -> str:
    """A declaration block cut at its top-level `:=` (i.e. its body).

    Bracket-depth aware, so a `:=` inside binders or a structure
    instance does not end the signature. Returns the whole block when
    there is no top-level `:=` (equation-style definitions)."""
    depth = 0
    for i in range(len(block) - 1):
        ch = block[i]
        if ch in _HEADER_OPEN:
            depth += 1
        elif ch in _HEADER_CLOSE:
            depth = max(0, depth - 1)
        elif ch == ":" and block[i + 1] == "=" and depth == 0:
            return block[:i].rstrip()
    return block.rstrip()


def declarations_in_scope(source: str, *, max_decls: int = 40,
                          max_chars: int = 400) -> list[str]:
    """The top-level declarations `source` puts in scope, as text.

    The prove step compiles each lemma against a header carrying the
    prelude, the theory's defs and every sibling lemma already proved —
    and then asked for the proof WITHOUT mentioning that any of it
    exists:
    p1963a2_dag_v4 proved `aux_odd_isRelPrime_two` at t=15007s and then
    failed `aux_isRelPrime_two_three` — one application of it — across
    seven attempts and two theory rounds.

    Proof bodies are dropped for theorems and lemmas: a name plus its
    statement is exactly what makes a lemma citable, and the proof is
    pure token cost. Definitions KEEP their body, because a def is only
    usable if you know what it unfolds to. Both are truncated, so one
    pathological declaration cannot crowd out the rest.
    """
    out: list[str] = []
    marks = list(_SCOPE_DECL_RE.finditer(source))
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(source)
        block = source[m.start():end].strip()
        if not block:
            continue
        if m.group("kind") in ("theorem", "lemma"):
            block = _signature_of(block)
        if len(block) > max_chars:
            block = block[:max_chars].rstrip() + " ..."
        out.append(block)
        if len(out) >= max_decls:
            break
    return out


