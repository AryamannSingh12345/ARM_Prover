    def _abduce_leaf(sketch: Sketch, h: HaveNode, err: str) -> bool:
        """RISING-SEA depth-2: invent helper lemmas for a stuck leaf,
        kernel-gate lemmas + new leaf tactic in ONE compile, and on
        success splice the lemmas into the working header. Soft-fails
        (False) on any LLM / parse / razor / gate problem — the caller
        falls through to decomposition or ordinary repair."""
        nonlocal theorem_header
        stmt = make_leaf_theorem(theorem_header, sketch, h)
        if stmt is None:
            return False
        try:
            raw = sketch_llm_call(
                ABDUCE_SYSTEM, abduce_user_prompt(stmt, err, premises))
        except Exception:
            return False
        raw_responses.append(raw)
        data = _extract_json_object(raw)
        if not isinstance(data, dict):
            repair_errors.append("abduce_not_applied: no JSON object")
            tr("abduce", id=h.id, status="rejected", detail="no JSON object")
            return False
        leaf_tac = _strip_leading_by(str(data.get("leaf_tactic") or ""))
        cand = data.get("lemmas") or []
        if not leaf_tac or not isinstance(cand, list) or not cand:
            repair_errors.append("abduce_not_applied: empty lemmas/tactic")
            tr("abduce", id=h.id, status="rejected",
               detail="empty lemmas/tactic")
            return False
        goal_norm = _norm_ws(h.type_text)
        decls: list[str] = []
        for c in cand:
            decl = str((c or {}).get("lemma_lean") or "").strip()
            if not decl or not _LEMMA_DECL_RE.match(decl):
                continue
            if _FORBIDDEN_TAC_RE.search(decl):
                repair_errors.append("abduce_not_applied: forbidden tactic")
                return False
            # Circularity razor: a lemma that contains the leaf's goal
            # verbatim is the goal-parking exploit, not a decomposition.
            if goal_norm and goal_norm in _norm_ws(decl):
                repair_errors.append(
                    "abduce_rejected_circular: "
                    + str((c or {}).get("name"))[:60])
                tr("abduce", id=h.id, status="lemma rejected (circular)",
                   detail=str((c or {}).get("name"))[:60])
                continue
            decls.append(decl)
        if not decls or _FORBIDDEN_TAC_RE.search(leaf_tac):
            return False
        lemmas_lean = "\n\n".join(decls)
        # ONE gate compile checks everything: the lemma proofs elaborate
        # sorry-free AND the new leaf tactic closes the leaf using them.
        cand_header = insert_lemmas_before_decl(theorem_header, lemmas_lean)
        leaf_hdr = make_leaf_theorem(cand_header, sketch, h)
        if leaf_hdr is None:
            return False
        gate = verify_fn(leaf_hdr, "  " + leaf_tac.replace("\n", "\n  "))
        if not gate.get("ok"):
            repair_errors.append(
                "abduce_gate_failed: "
                + (gate.get("errors") or "?")[:200])
            tr("abduce", id=h.id, status="kernel gate FAILED",
               detail=(gate.get("errors") or "?")[:300], lemmas=decls)
            return False
        theorem_header = cand_header
        h.tactic = leaf_tac
        abduced.append(h.id)
        abduced_lemma_decls.extend(decls)
        tr("abduce", id=h.id, status="ACCEPTED (kernel-gated)",
           lemmas=decls, detail=f"leaf tactic: {leaf_tac[:120]}")
        if lemma_library_path:
            # Telemetry only, never load-bearing; .lean dedup by decl
            # name, JSONL sidecar dedup by statement hash + provenance.
            _append_lemma_library(
                lemma_library_path, f"abduced for leaf `{h.id}`", decls,
                provenance=lemma_provenance)
        return True

    def _recognize_then_abduce(
            sketch: Sketch,
            broken: list[tuple[HaveNode, str]]) -> set[str]:
        """RECOGNITION FIRST, then theory.

        The prover's failures are largely REACH failures: `putnam_2020_a2`
        spent its whole budget on a reindexing `Finset.sum_range_succ'`
        performs in one step. Inventing a lemma that Mathlib already
        carries is the most expensive possible way to fail, so before any
        theory is proposed each stuck leaf is checked against what has
        already been proved.

        Cost is ONE compile per stuck leaf (every candidate is tried in a
        single `first | …`), against a theory loop that costs many. A
        recognised leaf is CLOSED — the tactic was kernel-accepted for
        that exact standalone statement — so its id is returned as fixed
        even if the theory loop later abandons the rest. Leaves that are
        not recognised fall through untouched.
        """
        if recognize_leaf_call is None:
            return _abduce_theory(sketch, broken)
        fixed: set[str] = set()
        remaining: list[tuple[HaveNode, str]] = []
        for h, err in broken:
            tac = None
            stmt = make_leaf_theorem(theorem_header, sketch, h)
            if stmt:
                try:
                    tac = recognize_leaf_call(stmt)
                except Exception:
                    tac = None
            if tac:
                h.tactic = tac
                fixed.add(h.id)
                tr("recognize", stage="LEAF_CLOSED", leaf=h.id)
            else:
                remaining.append((h, err))
        if not remaining:
            return fixed
        return fixed | _abduce_theory(sketch, remaining)

    def _abduce_theory(sketch: Sketch,
                       broken: list[tuple[HaveNode, str]]) -> set[str]:
        """Deferred theory abduction: statements → minimal cover →
        satisfaction probe → prove → commit. Returns the leaf ids
        fixed on full success; empty set on any abandonment (caller
        falls through to decomposition / sketch repair). All-or-
        nothing: sketch and header are mutated only on commit."""
        nonlocal theorem_header
        if probe_fn is None:
            repair_errors.append("theory_skipped: no probe_fn")
            return set()
        stuck: list[tuple[str, str, str]] = []
        for h, err in broken:
            stmt = make_leaf_theorem(theorem_header, sketch, h)
            if stmt is None:
                return set()
            stuck.append((h.id, stmt, err))
        broken_ids = {h.id for h, _ in broken}
        prelude = theorem_header[:_decl_offset(theorem_header)]

        def _satisfied(defs: list[str], lemma_stmts: list[tuple[str, str]],
                       tactics: dict[str, str],
                       _intro_retry_ok: bool = True) -> tuple[bool, str]:
            """Probe: with lemmas ASSUMED (sorry stubs), do all broken
            leaves close under the proposed tactics? Fails on any
            pre-body error (the theory itself doesn't elaborate) or
            any error attributed to a target leaf.

            `_intro_retry_ok` is internal: it caps the spurious-intro
            repair at ONE re-probe per call, so a pathological tactic
            cannot loop the verifier."""
            stubs = list(defs) + [s + " := by sorry"
                                  for _, s in lemma_stmts]
            cand_header = (insert_lemmas_before_decl(
                theorem_header, "\n\n".join(stubs))
                if stubs else theorem_header)
            trial = Sketch(
                haves=[HaveNode(x.id, x.type_text,
                                tactics.get(x.id, x.tactic),
                                list(x.depends))
                       for x in sketch.haves],
                # Closer-stuck mode: the closer is posed as a pseudo-leaf
                # (id CLOSER_ID), so its proposed tactic must actually
                # drive the probe.
                closer=tactics.get(CLOSER_ID, sketch.closer),
                setup=list(sketch.setup))
            body, segs = assemble_proof_with_map(
                trial, leaf_fallbacks=leaf_fallbacks,
                closer_fallback=closer_fallback)
            res = probe_fn(cand_header, body)
            errs_text = res.get("errors") or ""
            clean_errs = strip_warning_blocks(errs_text)
            offset = res.get("body_line_offset")
            if res.get("ok"):
                return True, ""
            # A TIMEOUT IS NOT A PASS. It carries no `file:line:col:`
            # markers, so `parse_error_locations` finds nothing,
            # `attribute_errors` blames no segment, and the "errors are
            # outside our leaves" branch below would return True —
            # reading "we learned nothing" as "the theory is satisfied".
            # Measured on p2020a2_recognize_0805: a 600s probe timeout
            # was gated OK, and the run then spent a 103s LLM call and a
            # further 600s compile proving a theory that had never been
            # validated. Fail closed: an unelaborable theory is one the
            # revision round should hear about.
            if _is_timeout_error(errs_text):
                return False, ("the theory did not elaborate within the "
                               "verifier's time budget — it is too heavy "
                               "to check, let alone prove. Propose fewer "
                               "or smaller lemmas.")
            if not isinstance(offset, int):
                return False, clean_errs[:1200]
            locs = parse_error_locations(errs_text)
            for line, msg in locs:
                if line - offset < 1:  # theory statements broken
                    return False, clean_errs[:1200]
            by_seg = attribute_errors(errs_text, segs, offset)
            bad = {k: v for k, v in by_seg.items() if k in broken_ids}
            if bad:
                # SPURIOUS-INTRO REPAIR (see strip_leading_intro).
                # The closer was posed standalone, so the model opened it
                # by introducing binders the sketch's setup already
                # introduced. Strip that line and re-probe ONCE. The
                # rewrite is written back into `tactics` so a theory that
                # goes on to commit carries the FIXED closer into the real
                # verify — probing a repair we then discard would fail
                # again at full compile.
                if _intro_retry_ok:
                    _by_id_all = {h.id: h for h in sketch.haves}
                    for _seg, _msgs in bad.items():
                        if not _INTRO_NO_BINDERS_RE.search(
                                "\n".join(_msgs[:3])):
                            continue
                        _node = _by_id_all.get(_seg)
                        _cur = tactics.get(_seg) or (
                            sketch.closer if _seg == CLOSER_ID
                            else (_node.tactic if _node else None))
                        _fixed = (strip_leading_intro(_cur) if _cur
                                  else None)
                        if _fixed is None:
                            continue
                        tactics[_seg] = _fixed
                        tr("abduce_theory",
                           stage="spurious-intro repair",
                           detail=(f"[{_seg}] dropped a leading `intro` "
                                   f"already performed by setup; "
                                   f"re-probing"))
                        return _satisfied(defs, lemma_stmts, tactics,
                                          _intro_retry_ok=False)
                return False, "\n".join(
                    f"[{k}] {v[0]}" for k, v in bad.items())[:1200]
            return True, ""  # remaining errors are outside our leaves

        def _decls_satisfy(defs: list[str], decls: list[str],
                           tactics: dict[str, str]) -> bool:
            """Probe with the REAL proved declarations (not sorry stubs):
            do all broken leaves still close, and do the kept decls all
            elaborate? Used by the opt-in post-minimisation compile check
            — a stricter `res.ok` is fine here because the only action on
            failure is reverting to the (known-good) full proved set."""
            stubs = list(defs) + list(decls)
            cand_header = (insert_lemmas_before_decl(
                theorem_header, "\n\n".join(stubs))
                if stubs else theorem_header)
            trial = Sketch(
                haves=[HaveNode(x.id, x.type_text,
                                tactics.get(x.id, x.tactic),
                                list(x.depends))
                       for x in sketch.haves],
                closer=tactics.get(CLOSER_ID, sketch.closer),
                setup=list(sketch.setup))
            body, _segs = assemble_proof_with_map(
                trial, leaf_fallbacks=leaf_fallbacks,
                closer_fallback=closer_fallback)
            try:
                res = probe_fn(cand_header, body)
            except Exception:
                return True  # cannot check → do not revert (no worse)
            return bool(res.get("ok"))

        prev_raw = ""
        failures: list[tuple[str, str]] = []
        #: Best partial state seen across revision rounds: (defs, proved
        #: names, proved decls, tactics, UNPROVED names) from the last
        #: round that proved SOMETHING but not everything. Used for the
        #: sufficiency-based partial commit when the rounds are
        #: exhausted — see there. The unproved names are carried so the
        #: commit can drop tactics that cite a lemma the kernel refused.
        _partial: tuple[list[str], list[str], list[str],
                        dict[str, str], list[str]] | None = None
        # Kernel-accepted lemma proofs persist ACROSS revision rounds,
        # keyed on the whitespace-normalized statement: a revised
        # theory never re-proves what the kernel already accepted.
        # This dict is the LEGACY cache — per-call, so it dies with an
        # abandoned theory. With `lemma_store` set, the same accepted
        # proofs go to the problem-scoped store instead and survive.
        proved_bank: dict[str, tuple[str, str]] = {}  # key -> (decl, name)

        def _bank_get(stmt: str) -> tuple[str, str] | None:
            if lemma_store is not None:
                rec = lemma_store.get(stmt, prelude)
                return (rec.decl, rec.name) if rec is not None else None
            return proved_bank.get(_norm_ws(stmt))

        def _bank_put(stmt: str, decl: str, dname: str,
                      t_round: int, defs: list[str] | None = None) -> None:
            if lemma_store is not None:
                # The theory's defs travel WITH the lemma: they only reach
                # the header on commit, so a lemma from an abandoned theory
                # is unusable without them (putnam_2020_a2_v1, t=3059s).
                lemma_store.put(stmt, dname, decl, prelude,
                                defs=tuple(defs or ()),
                                sketch_attempt=cur_attempt,
                                theory_round=t_round)
            else:
                proved_bank[_norm_ws(stmt)] = (decl, dname)

        def _reframe_proposal(stuck_one: list[tuple[str, str, str]],
                              prelude_txt: str,
                              t_round_now: int) -> str | None:
            """Ask for a CHANGE OF FRAME, rendered as a theory proposal.

            Returns theory-format JSON so the caller's existing pipeline
            judges it exactly like any other proposal, or None when no
            sufficient reframing was found (the caller then abandons, as
            it would have anyway).

            `propose_reframe` has already spent its own budget here: the
            leverage gate (free) rejected frames that merely move the
            difficulty, and the sufficiency probe (one compile) confirmed
            that GRANTING every claim the derivation closes the goal. So
            a proposal reaching the prove step is one already known to be
            worth proving.
            """
            leaf_id, stmt, _err = stuck_one[0]
            split = split_theorem_header(stmt)
            if split is None:
                return None
            from search.difficulty import estimate_difficulty
            from search.reframe import propose_reframe, theory_as_proposal
            try:
                res = propose_reframe(
                    stmt, split[1],
                    llm_call=sketch_llm_call,
                    probe_fn=probe_fn,
                    prelude=prelude_txt,
                    rounds=reframe_rounds,
                    premises=premises,
                    difficulty_fn=estimate_difficulty,
                    leverage_factor=reframe_leverage_factor,
                    trace=tr,
                )
            except Exception:
                return None
            if not res.sufficient or res.theory is None:
                repair_errors.append("reframe_not_applied: no sufficient frame")
                return None
            extra_defs, extra_claims = _reframe_support_library(
                res.theory, split[1], prelude_txt, t_round_now)
            tr("reframe", stage="proposal_to_theory", leaf=leaf_id,
               name=res.theory.name, n_objects=len(res.theory.objects),
               n_claims=len(res.theory.claims),
               n_lib_defs=len(extra_defs), n_lib_claims=len(extra_claims))
            return theory_as_proposal(res.theory, [leaf_id],
                                      extra_defs=extra_defs,
                                      extra_claims=extra_claims)

        def _reframe_support_library(
                theory, target_goal: str, prelude_txt: str,
                t_round_now: int) -> tuple[list[str], list[str]]:
            """Build a small library ABOUT the theory's new objects.

            A reframing introduces objects nothing is yet known about, so
            its bridges can be unprovable purely for lack of basic facts.
            This constructs those facts FIRST, each one individually
            kernel-verified by `build_library` (a failed declaration does
            not abort the build — a partial library still helps).

            Results are split BY KIND because the two proposal fields are
            not interchangeable: definitions go to `defs` (spliced
            verbatim), while proved lemmas are registered in the
            proved-lemma bank and returned as CLAIMS, so the prove step
            finds them already proved and spends ZERO compiles on them.
            Putting a proved lemma in `defs` instead would see it
            silently dropped by the def regex.

            EXPENSIVE: up to `decls x attempts` real compiles. Off by
            default, and it returns empty on any failure so the reframe
            proceeds exactly as it would without a library.
            """
            if not (reframe_build_library and theory.objects
                    and library_compile_fn is not None):
                return [], []
            objects = "\n\n".join(theory.objects)
            spec = (
                "Basic supporting facts about NEW objects just introduced "
                "to attack this goal:\n\n"
                f"    {target_goal}\n\n"
                "The objects are already in scope:\n\n"
                f"{objects}\n\n"
                "These claims still have to be proved about them:\n\n"
                + "\n".join(f"  - {c}" for c in theory.claims)
                + "\n\nBuild the elementary lemmas those claims need — "
                  "the facts a textbook would establish immediately after "
                  "defining these objects. Do NOT restate the claims "
                  "themselves.")
            lib_imports = (prelude_txt.rstrip() + "\n\n" + objects).strip()
            try:
                from search.library import build_library
                lib = build_library(
                    spec,
                    llm_call=sketch_llm_call,
                    verify_fn=lambda h, _b: library_compile_fn(h),
                    imports=lib_imports,
                    name=(theory.name or "ReframeSupport"),
                    max_decls=reframe_library_decls,
                    attempts_per_decl=reframe_library_attempts,
                    known=premises,
                    trace=tr,
                )
            except Exception:
                return [], []
            defs_out: list[str] = []
            claims_out: list[str] = []
            for d in lib.decls:
                if d.kind in ("lemma", "theorem"):
                    cut = d.source.find(":=")
                    stmt = d.source[:cut].rstrip() if cut > 0 else ""
                    if not stmt:
                        continue
                    # Register the KERNEL-VERIFIED proof so the prove step
                    # reuses it instead of re-deriving it.
                    _bank_put(stmt, d.source, d.name, t_round_now,
                              list(theory.objects))
                    claims_out.append(stmt)
                else:
                    defs_out.append(d.source)
            tr("reframe", stage="support_library",
               verified=len(lib.decls), failed=len(lib.failed),
               planned=lib.planned)
            return defs_out, claims_out

        # (recognition runs BEFORE this function — see
        # `_recognize_then_abduce`.)

        # REFRAME lives at the END of the theory loop, as one extra
        # proposal round reached only when every in-language round has
        # failed. Ordering is the whole point: abduction decomposes a
        # problem in its OWN vocabulary and is far cheaper, so changing
        # the frame is the escalation, never the first move.
        #
        # Restricted to a SINGLE stuck leaf: a reframing supplies one
        # derivation closing one goal, so with several broken leaves the
        # coverage check below would fail anyway — better to not spend
        # the calls.
        _reframe_round = -1
        if reframe_on_abandon and len(stuck) == 1:
            _reframe_round = abduce_theory_rounds + 1

        for t_round in range(abduce_theory_rounds + 1
                             + (1 if _reframe_round > 0 else 0)):
            if t_round == _reframe_round:
                raw = _reframe_proposal(stuck, prelude, t_round)
                if raw is None:
                    return set()
            else:
                user = (theory_user_prompt(stuck, premises) if t_round == 0
                        else theory_revise_prompt(prev_raw, failures, stuck,
                                                  premises,
                                                  lessons=seen_lessons))
                try:
                    raw = sketch_llm_call(THEORY_SYSTEM, user)
                except Exception:
                    return set()
            raw_responses.append(raw)
            prev_raw = raw
            parsed, perr = _parse_theory(raw)
            if parsed is None:
                repair_errors.append(f"theory_not_applied: {perr}")
                tr("abduce_theory", stage="rejected", detail=perr,
                   round=t_round)
                failures = [("<theory parse>", perr or "?")]
                continue
            defs, lemmas, tactics = parsed
            # REPAIR A: the theory's LEAF TACTICS get the same hygiene as
            # submitted lemma proofs. They are model-written tactic blocks
            # with the identical failure modes, and until now only the
            # prove step hardened them.
            #
            # MEASURED on p1963a2_dag_v1, sketch 2: FOUR consecutive theory
            # rounds died at the satisfaction gate on the same error —
            # `h_f1 has type f 1 = 1 but is expected to have type
            # 1 ≤ f 1` — a coercion in a TACTIC, not in any proposed
            # lemma. The model rewrote the lemma four times (~1700s of
            # probe compiles) because that is what the ledger invited.
            # The residual sweep closes `1 ≤ f 1` outright.
            if tactic_hygiene:
                tactics = {k: harden_tactic_block(v)
                           for k, v in tactics.items()}
            # ALREADY IN THE HEADER? `--store-feedback` splices proved
            # lemmas into `theorem_header`, and the theory loop then sees
            # them in its prompt and re-proposes them for proving. Lean
            # reports "has already been declared" — a HEADER error, which
            # kills the round. Measured on p2023a2_v1 at t=10932s:
            # `aux_equation_root_bridge` was spliced at attempt 3 and
            # re-proposed in round 2.
            #
            # This is the MIRROR of the fix in `_surface_store_lemmas`:
            # that one stops the splice re-declaring; this one stops the
            # proposal re-declaring. Such a lemma needs no proof — it is
            # already in scope — so it is dropped rather than rejected.
            _hdr_names = set(re.findall(
                r"(?m)^\s*(?:private\s+|protected\s+|noncomputable\s+)*"
                r"(?:theorem|lemma|def|abbrev|structure|inductive)\s+"
                r"([A-Za-z_][A-Za-z0-9_'!?₀-₉.]*)", theorem_header))
            if _hdr_names:
                _kept = [(nm, st) for nm, st in lemmas
                         if (_LEMMA_NAME_RE.match(st).group(1)
                             if _LEMMA_NAME_RE.match(st) else nm)
                         not in _hdr_names]
                if len(_kept) != len(lemmas):
                    tr("abduce_theory", stage="already in scope",
                       detail=f"{len(lemmas) - len(_kept)} proposed lemma(s) "
                              f"already declared in the header")
                    lemmas = _kept
            missing = broken_ids - set(tactics)
            if missing:
                tr("abduce_theory", stage="incomplete",
                   detail=f"no leaf_tactics for {sorted(missing)}",
                   round=t_round)
                failures = [("<coverage>",
                             f"leaf_tactics missing for leaves "
                             f"{sorted(missing)} — every stuck leaf "
                             f"needs a tactic")]
                continue
            tr("abduce_theory", stage="proposed", round=t_round,
               lemmas=[s for _, s in lemmas], defs=defs,
               detail=f"{len(lemmas)} lemmas, {len(defs)} defs")

            # CIRCULARITY GUARD: a lemma whose conclusion is a stuck
            # goal (or the main goal) restates the problem instead of
            # decomposing it. The satisfaction gate passes such lemmas
            # trivially ("assuming the theorem, the theorem holds") and
            # the prove step then faces the original problem — all six
            # b5_bare_v3 proposals were exactly this. Reject at parse
            # time, tell the revision WHY.
            # Point 7a: compare goal fingerprints, not raw whitespace-
            # stripped text. `circularity_mode='text'` (default) reproduces
            # the old _norm_ws behaviour exactly; 'syntactic' is
            # α-invariant (catches renamed-binder restatements); with a
            # defeq probe, 'elaborated' escalates to Lean definitional
            # equality. An undecidable probe is treated as NOT circular, so
            # escalation is never less safe than the syntactic mode.
            from search.goal_fingerprint import is_circular as _is_circular
            _goal_stmts = [_stmt for _lid, _stmt, _err in stuck]
            _goal_stmts.append(theorem_header)
            circular = []
            for _name, _s in lemmas:
                if _is_circular(_s, _goal_stmts, mode=circularity_mode,
                                split_fn=split_theorem_header,
                                defeq_probe=circularity_defeq_probe):
                    circular.append(_name or _s[:60])
            if circular:
                repair_errors.append(
                    "theory_circular: " + ", ".join(circular)[:160])
                tr("abduce_theory", stage="rejected (circular)",
                   round=t_round,
                   detail=f"restates a stuck goal: {circular}")
                failures = [(
                    "<circularity check — auto-rejected BEFORE any "
                    "compile>",
                    f"Lemma(s) {circular} merely RESTATE a stuck goal "
                    "(same conclusion). That is circular: proving them "
                    "IS the original problem. Decompose instead — "
                    "introduce the explicit construction the proof "
                    "needs (an ordering of the objects, an extremal/"
                    "minimizing choice, an invariant, an auxiliary "
                    "function) and state its properties as separate, "
                    "genuinely smaller lemmas.")]
                continue

            # DECOMPOSITION-QUALITY GATE (flag-gated, off by default): the
            # circularity guard rejects exact restatements, but a
            # non-circular lemma can still be theorem-sized (a
            # generalisation, an argument reorder, a lemma carrying ~90%
            # of the conclusion). The satisfaction gate would pass it and
            # the prove step would then face almost the original
            # difficulty. Reject cheaply — BEFORE any compile — a theory
            # whose hardest lemma is not meaningfully easier than the
            # hardest stuck obligation, and tell the revision why.
            if abduce_quality_gate:
                from search.difficulty import theory_reduces_difficulty
                _goal_texts = []
                for _lid, _stmt, _err in stuck:
                    _ps = split_theorem_header(_stmt)
                    if _ps is not None:
                        _goal_texts.append(_ps[1])
                _lemma_goals = []
                for _name, _s in lemmas:
                    _ps = split_theorem_header(_s)
                    _lemma_goals.append((_name, _ps[1] if _ps else _s))
                _qr = theory_reduces_difficulty(
                    _goal_texts, _lemma_goals,
                    factor=abduce_quality_factor,
                    prior_fn=provability_prior_fn)
                if not _qr.ok:
                    # PRUNE the offending lemma(s), keep the rest. Rejecting
                    # the whole proposal (the original behaviour) threw away
                    # good building-block lemmas whenever the model bundled
                    # one goal-sized capstone with them — observed killing
                    # every round on amc12a_2021_p25. Drop only the flagged
                    # lemmas; if a leaf tactic needed one, the satisfaction
                    # gate below fails and drives a targeted revision. Reject
                    # wholesale only when nothing survives.
                    _off = set(_qr.offenders)
                    _kept = [(n, s) for i, (n, s) in enumerate(lemmas)
                             if (n or f"lemma_{i}") not in _off]
                    repair_errors.append(
                        "theory_low_quality: " + _qr.reason[:180])
                    if not _kept:
                        tr("abduce_theory",
                           stage="rejected (all lemmas low quality)",
                           round=t_round, detail=_qr.reason,
                           quality=_qr.to_dict())
                        failures = [(
                            "<decomposition-quality gate — every proposed "
                            "lemma is ≈ as hard as the obligation>",
                            _qr.reason + ". Propose lemmas that each attack "
                            "a STRICTLY SMALLER sub-problem: remove a "
                            "quantifier, discharge one finite sum/term, fix "
                            "an ordering or invariant, or isolate a single "
                            "fact — not a lemma that re-expresses the whole "
                            "obligation.")]
                        continue
                    tr("abduce_theory", stage="pruned (low quality)",
                       round=t_round, detail=_qr.reason,
                       quality=_qr.to_dict(),
                       dropped=sorted(_off),
                       kept=[n for n, _ in _kept])
                    lemmas = _kept
                    # Fall through with the reduced set; the satisfaction
                    # gate decides whether the survivors still cover.

            # New idea → new vocabulary: give the runner a chance to
            # extend the import set for the proposed declarations
            # BEFORE the satisfaction probe compiles them.
            if refresh_imports_call is not None:
                try:
                    _itag = refresh_imports_call(
                        "\n\n".join(defs + [s for _, s in lemmas]))
                except Exception as _ie:
                    _itag = None
                    tr("imports_refresh", ok=False, round=t_round,
                       detail=f"{type(_ie).__name__}: {_ie}")
                if _itag:
                    tr("imports_refresh", ok=True, round=t_round,
                       detail=_itag)

            ok, gerr = _satisfied(defs, lemmas, tactics)
            if not ok:
                _note_lessons(gerr)
                repair_errors.append(f"theory_gate_failed: {gerr[:200]}")
                tr("abduce_theory", stage="gate FAILED", round=t_round,
                   detail=gerr[:400])
                # REPAIR B: the gate stubs every proposed lemma with
                # `sorry`, so its failure CANNOT be caused by a lemma's
                # content — the lemmas are assumed. The fault is always in
                # the leaf tactics, the closer, or the setup. Saying so
                # turns an ambiguous "the theory doesn't work" into the
                # one actionable statement available.
                #
                # MEASURED on p1963a2_dag_v1, sketch 2: four consecutive
                # rounds proposed four different lemmas and hit the SAME
                # tactic-level coercion error each time (`h_f1 : f 1 = 1`
                # used where `1 ≤ f 1` was wanted). The model optimised
                # the lemma because nothing told it the lemma was not the
                # problem.
                failures = [
                    ("<satisfaction gate — leaves do not close under the "
                     "assumed theory. NOTE: every lemma below was ASSUMED "
                     "(stubbed with `sorry`) for this check, so this error "
                     "CANNOT be caused by a lemma's statement or proof. "
                     "The fault is in a leaf TACTIC, the closer, or the "
                     "setup — fix those, and only restate a lemma if the "
                     "tactics genuinely need a different fact>", gerr)]
                continue
            tr("abduce_theory", stage="gate ok (leaves satisfied under "
                                      "assumed theory)", round=t_round)

            # PROVE the theory, one lemma at a time; earlier proved
            # lemmas (and defs) are in scope for later ones. NOTE:
            # proving comes BEFORE any minimization — a satisfaction-
            # driven pre-prove elimination dropped exactly the lemma
            # the leaf used on engel3 (and would happily discard the
            # building blocks later proofs need).
            proved_decls: list[str] = []
            proved_names: list[str] = []
            failures = []
            ledger: list[tuple[str, str]] = []
            any_failed = False
            for name, stmt in lemmas:
                dname = (_LEMMA_NAME_RE.match(stmt).group(1)
                         if _LEMMA_NAME_RE.match(stmt) else name)
                banked = _bank_get(stmt)
                if banked:
                    proved_decls.append(banked[0])
                    proved_names.append(banked[1])
                    ledger.append((f"lemma `{dname}`: PROVED in an "
                                   f"earlier round (cached, in scope — "
                                   f"do NOT restate or weaken)", ""))
                    continue
                ctx = "\n\n".join(defs + proved_decls)
                lemma_hdr = prelude + (ctx + "\n\n" if ctx else "") + stmt
                # What the COMPILER will see above this lemma — the
                # prelude (with any store lemmas spliced in), this
                # theory's defs, and every sibling already proved.
                # The prompt used to omit all of it, so the model
                # re-derived facts sitting three lines up the file.
                _in_scope = declarations_in_scope(
                    prelude + ("\n\n" + ctx if ctx else ""))
                perr2: str | None = None
                proof_text = ""
                proven = False
                asked_imports = False
                # Proof text -> the error it already earned. A model that
                # resubmits an identical proof cannot get a different
                # verdict, so the compile is pure waste. Measured on
                # p2020a2_recognize_0805: `aux_weightedChooseSum_succ`
                # received the SAME proof three times and paid three
                # compiles (229s + 283s + 331s) for one bit of
                # information.
                _seen_proofs: dict[str, str] = {}
                # Attempt budget. Legacy (`prove_retry_budget is None`) is
                # a flat two attempts whatever went wrong; with a budget
                # table the allowance is recomputed from the LATEST
                # failure's class after every attempt, so a lemma that
                # stops being a name problem and starts being a maths
                # problem is re-budgeted accordingly. `HARD_CAP` inside
                # `budget_for` bounds any reclassification sequence.
                fail_classes: list[str] = []
                _attempts = 0
                _max_attempts = _RB.LEGACY_ATTEMPTS
                while _attempts < _max_attempts:
                    _attempts += 1
                    # A parse failure means Lean never reached the
                    # mathematics, so ask for a minimal edit to the SAME
                    # proof rather than a fresh one.
                    _syntax_only = ("parse_error" in fail_classes
                                    and bool(proof_text))
                    try:
                        raw_p = sketch_llm_call(
                            PROVE_LEMMA_SYSTEM,
                            prove_lemma_prompt(
                                stmt, perr2, premises,
                                prev_proof=proof_text,
                                syntax_only=_syntax_only,
                                in_scope=_in_scope))
                    except Exception:
                        return set()
                    raw_responses.append(raw_p)
                    pobj = _extract_json_object(raw_p)
                    proof_text = _normalize_proof_indent(
                        _strip_leading_by(
                            str((pobj or {}).get("proof") or "")))
                    if (not proof_text
                            or _FORBIDDEN_TAC_RE.search(proof_text)):
                        perr2 = "empty or forbidden proof"
                        fail_classes = _RB.classify_prove_failure(
                            None, empty_or_forbidden=True)
                        if prove_retry_budget is not None:
                            # One attempt, then escalate via the ledger.
                            # Re-asking an identical question that already
                            # returned nothing is the single largest waste
                            # in the legacy loop (12 of 19 failures).
                            _max_attempts = _RB.budget_for(
                                fail_classes, prove_retry_budget)
                        continue
                    # REPEAT: identical proof text under an UNCHANGED
                    # environment cannot earn a different verdict. Skip
                    # the compile, keep the attempt, and say so — the
                    # previous error alone evidently read as "try again"
                    # rather than "try something else".
                    #
                    # "Unchanged environment" is load-bearing: an import
                    # refresh can make a byte-identical proof compile,
                    # which is precisely what the refresh is for, so the
                    # seen-set is cleared whenever imports move.
                    _pkey = _norm_ws(proof_text)
                    if _pkey in _seen_proofs:
                        perr2 = (
                            "you have ALREADY submitted this exact proof "
                            "and it failed with: "
                            + (_seen_proofs[_pkey] or "?")[:400]
                            + " — resubmitting it cannot succeed. Change "
                            "the APPROACH, or split the step you cannot "
                            "close into its own lemma.")
                        _note_lessons(perr2)
                        tr("abduce_theory", stage="duplicate proof skipped",
                           detail=dname)
                        continue
                    # Tactic hygiene (see harden_tactic_block): `try`-wrap
                    # no-op-prone normalisation tactics and sweep trivial
                    # residual goals. Cannot break a passing proof; on the
                    # measured b5 run this class accounted for 69% of lost
                    # lemma attempts. The BANKED text is the hardened one,
                    # since that is what the kernel accepted.
                    if tactic_hygiene:
                        proof_text = harden_tactic_block(proof_text)
                    gate = verify_fn(
                        lemma_hdr,
                        "  " + proof_text.replace("\n", "\n  "))
                    if gate.get("ok"):
                        proven = True
                        break
                    perr2 = (strip_warning_blocks(
                        gate.get("errors") or "") or "?")[:900]
                    _seen_proofs[_pkey] = perr2
                    _note_lessons(perr2)
                    fail_classes = _RB.classify_prove_failure(perr2)
                    if prove_retry_budget is not None:
                        _max_attempts = _RB.budget_for(
                            fail_classes, prove_retry_budget)
                    # Error-driven import refresh: an unknown name in a
                    # lemma proof is handed to the runner's import hook
                    # WITH the error, so the model can name the module
                    # and the retry proof can actually use the lemma it
                    # reached for. Once per lemma; entirely generic.
                    if (refresh_imports_call is not None
                            and not asked_imports
                            and _UNKNOWN_IDENT_RE.search(perr2)):
                        asked_imports = True
                        try:
                            _etag = refresh_imports_call(
                                stmt + "\n-- proof attempt failed with:\n"
                                + "".join(
                                    f"-- {ln}\n" for ln in
                                    perr2.splitlines()[:8]))
                        except Exception:
                            _etag = None
                        if _etag:
                            tr("imports_refresh", ok=True,
                               detail=f"error-driven: {_etag}")
                            # The ENVIRONMENT just changed, so the
                            # duplicate-proof guard's premise no longer
                            # holds: a proof that failed on an unknown
                            # name may now compile unchanged, and that is
                            # exactly the point of refreshing imports.
                            # Forget what was seen under the old imports.
                            _seen_proofs.clear()
                if proven:
                    decl = (f"{stmt} := by\n  "
                            + proof_text.replace("\n", "\n  "))
                    proved_decls.append(decl)
                    proved_names.append(dname)
                    _bank_put(stmt, decl, dname, t_round, defs)
                    ledger.append((f"lemma `{dname}`: PROVED "
                                   f"(verifier-accepted, in scope)", ""))
                    tr("abduce_theory", stage="lemma PROVED",
                       detail=stmt[:120])
                else:
                    any_failed = True
                    # Class-specific escalation rides the EXISTING revision
                    # ledger: the model is told what kind of failure this
                    # was, not just that it failed. Without a budget table
                    # the wording is byte-identical to the legacy entry.
                    _hint = (_RB.ledger_hint(fail_classes)
                             if prove_retry_budget is not None else "")
                    if _hint:
                        prove_retry_log.append(
                            f"{dname}: {'+'.join(fail_classes)} after "
                            f"{_attempts} attempt(s)")
                        ledger.append((f"lemma `{dname}`: PROOF FAILED "
                                       f"after {_attempts} attempt(s) — "
                                       f"{_hint}", perr2 or "?"))
                    else:
                        ledger.append((f"lemma `{dname}`: PROOF FAILED — "
                                       f"revise its statement, split it "
                                       f"into easier lemmas, or change "
                                       f"approach", perr2 or "?"))
                    tr("abduce_theory", stage="lemma proof FAILED",
                       detail=f"{stmt[:120]} — {(perr2 or '?')[:200]}",
                       classes=fail_classes, attempts=_attempts)
            if any_failed:
                # Remember what the kernel DID accept this round. A later
                # sufficiency probe may find the proved subset already
                # closes the stuck leaves, in which case discarding it
                # would throw away a finished proof — see the partial
                # commit after the rounds loop.
                if proved_decls:
                    # Also remember which proposed names the kernel did
                    # NOT accept. A leaf tactic citing one of those can
                    # never be part of a partial commit — see there.
                    _all_names = [
                        (_LEMMA_NAME_RE.match(_s).group(1)
                         if _LEMMA_NAME_RE.match(_s) else _n)
                        for _n, _s in lemmas]
                    _unproved = [x for x in _all_names
                                 if x not in set(proved_names)]
                    _partial = (list(defs), list(proved_names),
                                list(proved_decls), dict(tactics),
                                _unproved)
                repair_errors.append(
                    "theory_lemma_unproved: "
                    + "; ".join(w[:80] for w, e in ledger if e))
                # The full ledger — proved AND failed — goes back for
                # revision. Without it the model misdiagnosed which
                # lemma survived (arm_engel3_v2 round 1).
                failures = ledger
                continue

            # Minimal commit AFTER proving: drop proved lemmas that are
            # referenced neither by any leaf tactic nor by a KEPT
            # declaration's text. Pure text check — no extra compiles —
            # and proofs already in hand can never lose their building
            # blocks. Reverse iteration so a lemma referenced only by a
            # later (kept) proof registers as used.
            if abduce_minimize and len(proved_decls) > 1:
                full_names, full_decls = list(proved_names), list(proved_decls)
                used_text = "\n".join(tactics.values())
                kept_rev: list[tuple[str, str]] = []
                for dname, decl in reversed(
                        list(zip(proved_names, proved_decls))):
                    ref_space = used_text + "\n" + "\n".join(
                        d for _, d in kept_rev)
                    if re.search(rf"\b{re.escape(dname)}\b", ref_space):
                        kept_rev.append((dname, decl))
                    else:
                        tr("abduce_theory", stage="pruned (unreferenced "
                                                  "after proving)",
                           detail=decl[:120])
                if kept_rev:
                    kept_rev.reverse()
                    proved_names = [n for n, _ in kept_rev]
                    proved_decls = [d for _, d in kept_rev]
                # Point 7 (opt-in): the reference prune is TEXTUAL — sound
                # for direct references (lemmas only cite earlier ones) but
                # blind to a use mediated by notation, a macro, or a def.
                # With --abduce-minimize-verify, when a drop occurred,
                # probe the pruned set; if the leaves no longer close, the
                # prune removed something used indirectly → revert to the
                # full, known-good proved set (each lemma was individually
                # kernel-proved), rather than waste the round at final
                # verify. Reverting is never harmful — worst case keeps a
                # few extra lemmas.
                if (abduce_minimize_verify and probe_fn is not None
                        and len(proved_decls) < len(full_decls)):
                    ok_pruned = _decls_satisfy(defs, proved_decls, tactics)
                    if not ok_pruned:
                        tr("abduce_theory",
                           stage="prune reverted (compile check)",
                           detail=f"pruned set failed probe; restoring "
                                  f"{len(full_decls)} proved lemmas")
                        proved_names, proved_decls = full_names, full_decls

            # COMMIT: theory fully proved — splice real declarations,
            # apply leaf tactics, rejoin the normal verify loop.
            decls_text = "\n\n".join(defs + proved_decls)
            theorem_header = insert_lemmas_before_decl(
                theorem_header, decls_text)
            by_id = {h.id: h for h in sketch.haves}
            fixed: set[str] = set()
            for hid in broken_ids:
                if hid in by_id and hid in tactics:
                    by_id[hid].tactic = tactics[hid]
                    fixed.add(hid)
            if CLOSER_ID in broken_ids and CLOSER_ID in tactics:
                sketch.closer = tactics[CLOSER_ID]
                fixed.add(CLOSER_ID)
            abduced.extend(sorted(fixed))
            abduced_lemma_decls.extend(defs + proved_decls)
            tr("abduce_theory", stage="COMMITTED",
               detail=f"{len(proved_decls)} lemmas proved, "
                      f"{len(fixed)} leaves fixed", lemmas=proved_decls)
            if lemma_library_path:
                _append_lemma_library(
                    lemma_library_path,
                    f"theory-abduced for leaves {sorted(fixed)}",
                    defs + proved_decls,
                    provenance=lemma_provenance)
            return fixed
        # PARTIAL COMMIT ON SUFFICIENCY.
        #
        # All-or-nothing asks "did every PROPOSED lemma prove?" when the
        # question that matters is "do the PROVED lemmas close the stuck
        # leaves?". Those differ whenever the model proposes scaffolding
        # for a lemma it then proves directly.
        #
        # MEASURED on putnam_1967_b5 (t=46563s): the crux lemma
        # `aux_weighted_transform` was kernel-PROVED, and the theory was
        # discarded anyway because three helper lemmas — written only to
        # support it — had failed. Ten proved lemmas sat unused while the
        # run continued for another two hours.
        #
        # SOUNDNESS: this cannot manufacture a solve. The subset is
        # committed only if the ordinary satisfaction probe passes with
        # those declarations spliced for real, and the assembled proof
        # still faces the normal verify loop and a final fresh compile.
        # Worst case is one wasted probe.
        if _partial is not None:
            _pdefs, _pnames, _pdecls, _ptactics, _punproved = _partial
            # A tactic that NAMES a lemma the kernel rejected cannot be
            # committed: the probe would die on `unknown identifier`,
            # which says nothing about whether the proved subset
            # suffices. MEASURED on p1963a2_dag_v2 — the partial commit
            # spent a 455s probe to fail on
            # `Unknown identifier aux_monotone_multiplicative_power_classification`,
            # the one lemma that had not proved. Drop those tactics so
            # the probe tests SUFFICIENCY, which is the actual question.
            _dropped = sorted(k for k, v in _ptactics.items()
                              if tactic_cites(v, _punproved))
            _ptactics = {k: v for k, v in _ptactics.items()
                         if k not in set(_dropped)}
            if _dropped:
                tr("abduce_theory", stage="partial commit filtered",
                   detail=(f"dropped {len(_dropped)} tactic(s) citing "
                           f"unproved lemmas: {_dropped}"))
            # Nothing left to test — skip the probe rather than spend a
            # full compile confirming we have no candidate.
            if not _ptactics:
                tr("abduce_theory", stage="partial commit skipped",
                   detail=("every stuck leaf's tactic cites a lemma that "
                           "did not prove; no subset to test"))
                _ok, _perr = False, "no tactic survives the unproved-lemma filter"
            else:
                _ok, _perr = _satisfied(_pdefs + _pdecls, [], _ptactics)
            if _ok:
                theorem_header = insert_lemmas_before_decl(
                    theorem_header, "\n\n".join(_pdefs + _pdecls))
                by_id = {h.id: h for h in sketch.haves}
                fixed = set()
                for hid in broken_ids:
                    if hid in by_id and hid in _ptactics:
                        by_id[hid].tactic = _ptactics[hid]
                        fixed.add(hid)
                if CLOSER_ID in broken_ids and CLOSER_ID in _ptactics:
                    sketch.closer = _ptactics[CLOSER_ID]
                    fixed.add(CLOSER_ID)
                abduced.extend(sorted(fixed))
                abduced_lemma_decls.extend(_pdefs + _pdecls)
                tr("abduce_theory", stage="PARTIAL COMMIT (proved subset "
                                          "suffices)",
                   detail=f"{len(_pdecls)} of the proposed lemmas proved; "
                          f"{len(fixed)} leaves fixed",
                   lemmas=_pdecls)
                if lemma_library_path:
                    _append_lemma_library(
                        lemma_library_path,
                        f"theory-abduced (partial) for leaves {sorted(fixed)}",
                        _pdefs + _pdecls,
                        provenance=lemma_provenance)
                return fixed
            tr("abduce_theory", stage="partial commit rejected",
               detail=(_perr or "proved subset does not close the leaves")[:200])

        repair_errors.append("theory_revision_exhausted")
        # The theory did not commit, but every lemma the kernel accepted
        # along the way is already in the problem-scoped store and stays
        # available to the next theory / sketch attempt. Under the legacy
        # per-call cache all of it was discarded here.
        _kept = (lemma_store.names() if lemma_store is not None else [])
        tr("abduce_theory", stage="abandoned",
           detail=("revision rounds exhausted"
                   + (f"; {len(_kept)} proved lemma(s) retained in the "
                      f"run-scoped store: {_kept}" if _kept else "")),
           retained=_kept)
        return set()

    def _decompose_leaf(sketch: Sketch, h: HaveNode) -> bool:
        """Replace a stubborn leaf's tactic with an assembled sub-DAG.
        Soft-fails (False) on any LLM/parse/topo problem — the caller
        falls through to ordinary repair for that leaf."""
        stmt = make_leaf_theorem(theorem_header, sketch, h)
        if stmt is None:
            return False
        try:
            raw_sub = sketch_llm_call(
                SKETCH_SYSTEM, sketch_user_prompt(stmt, premises))
        except Exception:
            return False
        raw_responses.append(raw_sub)
        sub, _perr = parse_sketch(raw_sub)
        if sub is None or not sub.haves:
            tr("decompose", id=h.id, ok=False,
               detail=f"sub-sketch unusable: {_perr or 'no haves'}")
            return False  # empty sub-sketch = no decomposition value
        sub_sorted, _terr = topo_sort(sub.haves)
        if sub_sorted is None:
            tr("decompose", id=h.id, ok=False, detail=_terr)
            return False
        sub.haves = sub_sorted
        h.tactic = assemble_proof(
            sub, leaf_fallbacks=leaf_fallbacks,
            closer_fallback=closer_fallback,
        )
        tr("decompose", id=h.id, ok=True,
           sub_haves=[f"{s.id} : {s.type_text}" for s in sub.haves])
        return True

    if sketch_mode not in ("tactics", "blueprint"):
        raise ValueError(f"unknown sketch_mode: {sketch_mode!r}")
    # Probe rejections carried across sketch attempts, so a regenerated
    # blueprint is told what was already found insufficient.
    _bp_failures: list[str] = []

    def _blueprint_sufficient(sk) -> tuple[bool, str]:
        """Assume every claim (sorry stubs) — does the closer close the goal?

        HONEST LIMIT: this tests the blueprint TOGETHER WITH the proposed
        closer, not logical entailment. A sound plan with a weak closer
        fails here. The closer therefore gets the fallback ladder, and a
        rejection is reported as "this plan + this closer does not close",
        which is what the model is asked to fix.

        Sorry stubs make this cheap and it can never manufacture a solve:
        `probe_fn` is errors-only and its verdict is never a proof.
        """
        if probe_fn is None:
            return True, ""          # cannot check → do not block
        trial = Sketch(
            haves=[HaveNode(h.id, h.type_text, "sorry", list(h.depends))
                   for h in sk.haves],
            closer=sk.closer, setup=list(sk.setup))
        body, _segs = assemble_proof_with_map(
            trial, leaf_fallbacks=(), closer_fallback=False)
        try:
            res = probe_fn(theorem_header, body)
        except Exception:
            return True, ""          # probe blew up → do not block
        if res.get("ok"):
            return True, ""
        return False, strip_warning_blocks(res.get("errors") or "")[:1200]

    def _generate_blueprint_sketch(attempt: int):
        """Blueprint → `Sketch` with empty tactics, or (None, reason)."""
        from search.blueprint import generate_blueprint
        bp, err = generate_blueprint(
            theorem_header,
            llm_call=sketch_llm_call,
            premises=premises,
            sequential=blueprint_sequential,
            trace=tr,
        )
        if bp is None:
            return None, f"blueprint: {err}"
        raw_responses.append(json.dumps(bp, ensure_ascii=False))
        haves = [HaveNode(c["id"], c["type"], "", list(c["depends"]))
                 for c in bp["claims"]]
        return Sketch(haves=haves, closer=bp["closer"],
                      raw_response="", setup=list(bp["setup"])), None

    #: Store decls already spliced into `theorem_header`, so a later
    #: attempt does not splice them twice.
    _store_spliced: set[str] = set()

    def _surface_store_lemmas() -> list[str]:
        """Splice kernel-proved store lemmas into the header so the NEXT
        sketch can build on them.

        Without this the store only prevents re-PROVING an identical
        statement (`_bank_get` is an exact-statement lookup inside the
        theory loop) — it never tells the sketcher the lemma exists. On
        putnam6_easy_v2 that cost the run: `aux_powerSum_recurrence`, the
        degree-3 recurrence the whole problem turns on, was kernel-proved
        at t=9372s, retained by the store at t=11734s, and then sketch
        attempt 3 started from scratch and never referenced it.

        Splicing is sound: each decl was accepted by the verifier under
        this prelude, and the store only returns records whose imports the
        current set still covers. Because the sketch prompt embeds the
        header, the model SEES them for free — no prompt change needed.
        Returns the names newly put in scope.
        """
        nonlocal theorem_header
        if lemma_store is None:
            return []
        # ALREADY IN THE HEADER? A lemma that a theory COMMITTED is written
        # straight into `theorem_header` by the commit path, which never
        # touches `_store_spliced` — so dedup on the spliced-set alone
        # re-declares it and the header dies with "has already been
        # declared". That aborts the run outright (header errors stop the
        # repair loop by design). Measured on p1968a1_v1: 5 lemmas
        # committed at t=16910s, the same 5 re-spliced at t=17401s, run
        # dead at t=17992s with NINE proved lemmas in hand.
        _declared = set(re.findall(
            r"(?m)^\s*(?:private\s+|protected\s+|noncomputable\s+)*"
            r"(?:theorem|lemma|def|abbrev|structure|inductive)\s+"
            r"([A-Za-z_][A-Za-z0-9_'!?₀-₉.]*)", theorem_header))
        # A lemma proved under one version of a def is NOT valid under a
        # different version of the same-named def, and `required_defs()`
        # keeps only the first-seen body per name — so records needing a
        # superseded body are dropped rather than surfaced into a header
        # where their def means something else.
        _incompat = lemma_store.incompatible_names()
        fresh = [r for r in lemma_store.records()
                 if r.key not in _store_spliced and r.name not in _declared
                 and r.name not in _incompat]
        if _incompat:
            tr("store_feedback", stage="records withheld",
               detail=(f"{len(_incompat)} stored lemma(s) depend on a "
                       f"superseded def body: {sorted(_incompat)}"))
        if not fresh:
            return []
        # Defs FIRST. The lemmas are stated in terms of them, and a theory's
        # defs only reach the header on COMMIT — so lemmas proved inside an
        # abandoned theory reference identifiers that do not exist. Splicing
        # them alone turns the header into a hard error
        # ("Unknown identifier `aux_weighted`", and under autoImplicit
        # "Function expected … ?m.1"), which stops the repair loop outright:
        # that is how this feature killed putnam_2020_a2_v1 at t=3059s with
        # 7 proved lemmas in hand.
        def _decl_name(src: str) -> str:
            m = re.match(r"\s*(?:private\s+|protected\s+|noncomputable\s+)*"
                         r"(?:def|abbrev|structure|inductive)\s+"
                         r"([A-Za-z_][A-Za-z0-9_'!?₀-₉.]*)", src)
            return m.group(1) if m else ""

        # `_declared` is the header BEFORE this splice, so filtering on it
        # alone cannot stop two same-named defs arriving in the SAME batch.
        # `_batch` closes that: one declaration per name, per splice.
        _batch: set[str] = set()
        blocks = []
        for d in lemma_store.required_defs():
            if not d.strip() or d in _store_spliced:
                continue
            nm = _decl_name(d)
            if nm and (nm in _declared or nm in _batch):
                continue
            if nm:
                _batch.add(nm)
            blocks.append(d)
        _store_spliced.update(blocks)
        blocks += [r.decl for r in fresh]
        theorem_header = insert_lemmas_before_decl(
            theorem_header, "\n\n".join(blocks))
        _store_spliced.update(r.key for r in fresh)
        return [r.name for r in fresh]

    for attempt in range(1, sketch_attempts + 1):
        cur_attempt = attempt
        if store_feedback and attempt > 1:
            _surfaced = _surface_store_lemmas()
            if _surfaced:
                tr("store_feedback", attempt=attempt, names=_surfaced,
                   detail=f"{len(_surfaced)} proved lemma(s) spliced into "
                          f"the header and now visible to the sketcher")
        tr("sketch_attempt", attempt=attempt, of=sketch_attempts,
           mode="fresh" if attempt == 1 else "retry_with_error_feedback")
        if sketch_mode == "blueprint":
            # Statements-first: plan the claims, leave every tactic empty
            # (the assembler turns an empty tactic into `first | <ladder>`),
            # then let the sufficiency probe below check the plan BEFORE
            # anything is proved. See search/blueprint.py for why.
            sketch, parse_err = _generate_blueprint_sketch(attempt)
            raw = raw_responses[-1] if raw_responses else ""
            last_response = raw
        else:
            if attempt == 1:
                user = sketch_user_prompt(theorem_header, premises)
            else:
                user = sketch_retry_prompt(theorem_header, last_response,
                                             last_error or "", premises)
            try:
                raw = sketch_llm_call(SKETCH_SYSTEM, user)
            except Exception as e:
                tr("llm_error", detail=f"{type(e).__name__}: {e}")
                return _final(None, None, "llm",
                              f"{type(e).__name__}: {e}", attempt)
            raw_responses.append(raw)
            last_response = raw

            sketch, parse_err = parse_sketch(raw)
        if sketch is None:
            last_error = f"sketch parse error: {parse_err}"
            tr("sketch_parse_error", error=parse_err, attempt=attempt)
            if attempt == sketch_attempts:
                return _final(None, None, "parse", parse_err, attempt)
            continue

        sorted_haves, topo_err = topo_sort(sketch.haves)
        if sorted_haves is None:
            last_error = f"topo error: {topo_err}"
            tr("topo_error", error=topo_err, attempt=attempt)
            if attempt == sketch_attempts:
                return _final(sketch, None, "topo", topo_err, attempt)
            continue
        sketch.haves = sorted_haves
        tr("sketch_parsed", attempt=attempt, n_haves=len(sketch.haves),
           ids=[h.id for h in sketch.haves],
           haves=[{"id": h.id, "type": h.type_text, "tactic": h.tactic,
                   "depends": list(h.depends)} for h in sketch.haves],
           setup=list(sketch.setup), closer=sketch.closer)

        if sketch_mode == "blueprint":
            # Check the PLAN before proving any of it. A blueprint whose
            # claims (even granted for free) do not close the goal is
            # regenerated with the probe's Lean errors fed back — the
            # legacy contract discovers this only at final verify, and
            # cannot tell it apart from bad tactics.
            _bp_ok, _bp_err = _blueprint_sufficient(sketch)
            _bp_round = 0
            while not _bp_ok and _bp_round < blueprint_rounds:
                _bp_round += 1
                _bp_failures.append(
                    "Granting every claim as proved, your closer still did "
                    "not close the goal. Lean reported:\n" + _bp_err)
                tr("blueprint", stage="insufficient", attempt=attempt,
                   round=_bp_round, detail=_bp_err[:400])
                repair_errors.append(f"blueprint_insufficient: {_bp_err[:120]}")
                _regen, _rerr = _generate_blueprint_sketch(attempt)
                if _regen is None:
                    tr("blueprint", stage="regen_failed", detail=_rerr)
                    break
                _sorted, _terr = topo_sort(_regen.haves)
                if _sorted is None:
                    tr("blueprint", stage="regen_topo_failed", detail=_terr)
                    break
                _regen.haves = _sorted
                sketch = _regen
                last_response = raw_responses[-1]
                tr("sketch_parsed", attempt=attempt,
                   n_haves=len(sketch.haves),
                   ids=[h.id for h in sketch.haves],
                   haves=[{"id": h.id, "type": h.type_text,
                           "tactic": h.tactic, "depends": list(h.depends)}
                          for h in sketch.haves],
                   setup=list(sketch.setup), closer=sketch.closer)
                _bp_ok, _bp_err = _blueprint_sufficient(sketch)
            tr("blueprint", stage="sufficient" if _bp_ok
                                 else "proceeding despite insufficiency",
               attempt=attempt, rounds_used=_bp_round)

        body = ""
        res: dict = {}
        prev_repair_raw: str | None = None
        # Per-attempt: consecutive rounds each leaf has been broken, and
        # decompositions/abductions spent per leaf.
        broken_streak: dict[str, int] = {}
        decompose_spent: dict[str, int] = {}
        abduce_spent: dict[str, int] = {}
        portfolio_spent: dict[str, int] = {}
        theory_spent = False  # one theory-abduction attempt per sketch
        # REPAIR C: a COMMITTED theory earns one extra repair round.
        #
        # A commit is the most expensive and most informative event in the
        # loop — it splices kernel-proved declarations into the header and
        # rewrites leaf tactics, so the proof afterwards is materially
        # different from the one whose failures set the budget. Landing on
        # the final round therefore wastes it: there is no iteration left
        # to build on what was just proved.
        #
        # MEASURED on p1963a2_dag_v1, sketch 1: the theory fired on round
        # 2 of 2, proved `aux_strictMonoOn_succ_growth`, committed, and
        # FIXED `h_lower` — the obstacle that had blocked both prior
        # rounds. The closer (a separate, independently broken segment)
        # then got exactly one un-iterated shot before
        # "repair rounds exhausted".
        #
        # Bounded at one bonus per sketch attempt, so worst case is a
        # single extra compile.
        _MAX_BONUS_ROUNDS = 1
        _bonus_granted = 0
        for round_no in range(repair_rounds + 1 + _MAX_BONUS_ROUNDS):
            body, segments = assemble_proof_with_map(
                sketch,
                leaf_fallbacks=leaf_fallbacks,
                closer_fallback=closer_fallback,
            )
            tr("assembled", round=round_no, attempt=attempt,
               body_lines=len(body.splitlines()),
               segments=[list(s) for s in segments], body=body)
            # SELF-REFERENCE: a body citing the theorem it proves makes
            # Lean treat the declaration as recursive ("fail to show
            # termination"), which is a HEADER error and aborts the whole
            # attempt. Catch it BEFORE the compile — the verdict is known,
            # and the round is worth more than the ~200-600s it would cost
            # to be told. p1967a2_v1 lost sketches 2 and 3 to exactly this.
            _self_ref = references_own_name(theorem_header, body)
            if _self_ref:
                tr("self_reference", attempt=attempt, round=round_no,
                   name=_self_ref)
                res = {"ok": False, "body_line_offset": 0, "errors": (
                    f"the proof refers to `{_self_ref}`, the theorem being "
                    f"proved. Lean then elaborates the declaration as "
                    f"RECURSIVE and reports \"fail to show termination\". "
                    f"Derive the goal from the hypotheses; never cite the "
                    f"goal itself.")}
            else:
                res = verify_fn(theorem_header, body)
            if res.get("ok"):
                return DagResult(
                    sketch=sketch, assembled_proof=body, verified=True,
                    failure_stage=None, failure_detail=None,
                    sketch_attempts=attempt,
                    leaf_fallback_used=bool(leaf_fallbacks),
                    raw_responses=raw_responses,
                    repair_rounds_used=total_repair_rounds,
                    repaired_ids=sorted(set(repaired_ids)),
                    leaf_closer_fixed_ids=sorted(set(leaf_closer_fixed)),
                    decomposed_ids=sorted(set(decomposed)),
                    repair_errors=repair_errors,
                    abduced_ids=sorted(set(abduced)),
                    abduced_lemmas=list(abduced_lemma_decls),
                    # A SOLVE is the row that most needs to say what it
                    # depended on. These four were recorded on the failure
                    # path (`_final`) and dropped here, so an audit could
                    # not rebuild the very proofs being counted.
                    lemma_store_stats=(lemma_store.stats()
                                       if lemma_store is not None else None),
                    lemma_store_kept=([r.decl for r in lemma_store.records()]
                                      if lemma_store is not None else []),
                    prove_retry_log=list(prove_retry_log),
                    verified_header=theorem_header,
                )
            if round_no >= repair_rounds + _bonus_granted:
                tr("repair_break", reason="repair rounds exhausted")
                break
            offset = res.get("body_line_offset")
            if not isinstance(offset, int):
                tr("repair_break",
                   reason="verify_fn gave no body_line_offset — "
                          "outer retry only")
                break  # runner doesn't localize — outer retry only
            errs = attribute_errors(res.get("errors") or "", segments, offset)
            tr("error_attribution",
               by_segment={k: [m[:400] for m in v] for k, v in errs.items()})
            # Point 7 (opt-in): CAUSAL attribution. Line-mapping is
            # syntactic — one source line's error can be collateral of a
            # dependency declared earlier, so a healthy leaf gets blamed
            # and repair rewrites a correct tactic. When enabled, each
            # blamed leaf is independently probe-compiled STANDALONE in
            # its dependency context (make_leaf_theorem: original binders
            # + depends-haves as hypotheses). A leaf that closes on its
            # own is exonerated: its messages reroute to the closer (the
            # existing conservative catch-all), so repair works on the
            # real culprit instead. Costs one probe per blamed leaf per
            # round — that is why it is off by default. Probe failures
            # (None/raise) never exonerate.
            if causal_attribution and probe_fn is not None and errs:
                by_id = {h.id: h for h in sketch.haves}
                for _lid in [k for k in list(errs) if k in by_id]:
                    _h = by_id[_lid]
                    _stmt = make_leaf_theorem(theorem_header, sketch, _h)
                    if _stmt is None:
                        continue
                    try:
                        _pr = probe_fn(
                            _stmt, "  " + _h.tactic.replace("\n", "\n  "))
                    except Exception:
                        continue
                    if _pr.get("ok"):
                        msgs = errs.pop(_lid)
                        errs.setdefault(CLOSER_ID, []).extend(msgs)
                        tr("causal_attribution", id=_lid, exonerated=True,
                           detail="leaf closes standalone in dependency "
                                  "context; blame rerouted to closer")
                    else:
                        tr("causal_attribution", id=_lid, exonerated=False)
            # Error-driven import refresh, main-loop edition: unknown
            # names in ANY segment (closer included — b5_bare_v2 died on
            # `Unknown identifier dist_add_dist_eq_iff` in the closer,
            # which the prove-lemma-only hook never saw). Generic
            # pattern, one ask per distinct error set.
            if refresh_imports_call is not None and errs:
                unk = [m for msgs in errs.values() for m in msgs
                       if _UNKNOWN_IDENT_RE.search(m)]
                unk_key = "|".join(sorted({m[:120] for m in unk}))
                if unk and unk_key not in imports_asked:
                    imports_asked.add(unk_key)
                    try:
                        _rtag = refresh_imports_call(
                            "-- Lean errors from the current proof "
                            "attempt:\n" + "".join(
                                f"-- {m[:200]}\n" for m in unk[:6]))
                    except Exception:
                        _rtag = None
                    if _rtag:
                        tr("imports_refresh", ok=True,
                           detail=f"repair-loop error-driven: {_rtag}")
            # Setup-block errors get their own repair channel (pass 3):
            # the old closer-channel merge showed the model the error but
            # gave it no way to APPLY a setup fix — the `NeZero S.card`
            # instance failure sat unrepaired for all of b5_bare_v1.
            setup_errs = errs.pop(SETUP_ID, None)
            setup_broken = bool(setup_errs)
            header_errs = errs.pop(HEADER_ID, None)
            if header_errs:
                # The statement (or spliced theory) did not elaborate.
                # No sketch repair can fix it, and every OTHER error in
                # this compile is downstream noise of the broken header
                # — chasing it replaces good tactics with garbage (the
                # arm_engel3_final1 run rewrote its correct `exact goal`
                # closer off the back of a header cascade). Record
                # loudly and stop repairing.
                repair_errors.append(
                    f"header_level_error: {header_errs[0][:200]}")
                tr("header_error", detail=header_errs[0][:300])
                tr("repair_break",
                   reason="header-level error — statement/theory cannot "
                          "be fixed by sketch repair; remaining error "
                          "attribution is unreliable")
                break
            if not errs and not setup_broken:
                # Bare timeouts (and any failure with no parseable
                # error locations) starve both repair and the leaf-
                # stuck theory trigger — the engel3 pathology, hit
                # three times in one run. In theory mode, spend the
                # one theory attempt treating ALL leaves as stuck: a
                # reformulation can fix a certificate blow-up that no
                # repair round ever could. (`setup_broken` alone is
                # still repairable — don't burn the theory shot on it.)
                _refresh_plan(has_attributable_errors=False, broken_pairs=[],
                              closer_broken=False, setup_broken=False,
                              theory_spent_now=theory_spent)
                if (_plan_ok(STAGE_BARE_TIMEOUT_THEORY)
                        and abduce_lemmas and abduce_mode == "theory"
                        and not theory_spent and probe_fn is not None
                        and sketch.haves):
                    theory_spent = True
                    t_err = (strip_warning_blocks(res.get("errors") or "")
                             or "bare timeout")[:900]
                    tr("abduce_theory",
                       stage="bare-timeout trigger — all leaves "
                             "treated as stuck")
                    fixed_ids = _recognize_then_abduce(
                        sketch, [(h, t_err) for h in sketch.haves])
                    if fixed_ids:
                        repaired_ids.extend(sorted(fixed_ids))
                        total_repair_rounds += 1
                        continue  # reverify with the committed theory
                tr("repair_break",
                   reason="nothing repairable in the body — outer retry")
                break  # nothing repairable in the body — outer retry only
            closer_broken = CLOSER_ID in errs
            broken_ids = {k for k in errs if k != CLOSER_ID}
            for bid in broken_ids:
                broken_streak[bid] = broken_streak.get(bid, 0) + 1
            if closer_broken:
                broken_streak[CLOSER_ID] = (
                    broken_streak.get(CLOSER_ID, 0) + 1)
            tr("repair_round", round=round_no + 1,
               broken=sorted(broken_ids), closer_broken=closer_broken,
               setup_broken=setup_broken)
            broken = [(h, "\n".join(errs[h.id])) for h in sketch.haves
                      if h.id in broken_ids]
            intact = [h for h in sketch.haves if h.id not in broken_ids]
            did_anything = False

            # Pass 1 — specialized leaf closer (Goedel-class) on each
            # broken leaf, posed standalone. Cheap, so it goes first.
            _refresh_plan(has_attributable_errors=True, broken_pairs=broken,
                          closer_broken=closer_broken,
                          setup_broken=setup_broken,
                          theory_spent_now=theory_spent)
            if _plan_ok(STAGE_LEAF_CLOSER) and leaf_closer_call is not None \
                    and broken:
                still_broken: list[tuple[HaveNode, str]] = []
                for h, err in broken:
                    stmt = make_leaf_theorem(theorem_header, sketch, h)
                    tac = ""
                    if stmt is not None:
                        try:
                            tac = (leaf_closer_call(stmt) or "").strip()
                        except Exception:
                            tac = ""
                    if tac and not _FORBIDDEN_TAC_RE.search(tac):
                        h.tactic = tac
                        leaf_closer_fixed.append(h.id)
                        repaired_ids.append(h.id)
                        intact.append(h)
                        did_anything = True
                        tr("leaf_closer", id=h.id, fixed=True, tactic=tac)
                    else:
                        still_broken.append((h, err))
                        tr("leaf_closer", id=h.id, fixed=False)
                broken = still_broken

            # Pass 1.25 — DETERMINISTIC LEAF PORTFOLIO (Point 3, opt-in):
            # the step pipeline's candidate machinery (proof prior /
            # tactic templates / dependency exploration) proposes tactics
            # for each broken leaf, combined into one `first | …`.
            #
            # VERIFY-BEFORE-CONSUME (fixes the ablate_easy_portfolioON
            # regression): the combined tactic is compile-tested on the
            # leaf posed STANDALONE (make_leaf_theorem) before it is
            # accepted. The leaf is claimed (removed from `broken`) ONLY if
            # that probe closes it; otherwise the leaf stays broken and the
            # normal ladder (theory / decompose / LLM repair) handles it as
            # if the portfolio never ran. This makes low-quality or even
            # unparseable candidates STRICTLY HARMLESS — a garbage
            # `first | …` just fails the probe and is discarded, instead of
            # poisoning a repairable leaf. Needs a verifier (probe_fn, else
            # verify_fn); one probe per broken leaf, once per leaf
            # (portfolio_spent). Empty `leaf_solvers` (the default) = this
            # pass does not exist.
            _pf = probe_fn or verify_fn
            if leaf_solvers and broken and _pf is not None:
                still_broken_p: list[tuple[HaveNode, str]] = []
                for h, err in broken:
                    if portfolio_spent.get(h.id, 0) >= 1:
                        still_broken_p.append((h, err))
                        continue
                    portfolio_spent[h.id] = 1
                    from search.dag.model import ObligationState
                    ob = ObligationState(
                        id=h.id, goal_text=h.type_text,
                        dependencies=tuple(h.depends))
                    cands: list[tuple[float, str, str]] = []
                    for prov in leaf_solvers:
                        try:
                            for c in prov.candidates(ob, solver_context):
                                cands.append(
                                    (float(c.cost), c.tactic, c.source))
                        except Exception as _pe:
                            tr("portfolio", id=h.id, provider=prov.name,
                               error=f"{type(_pe).__name__}: {_pe}")
                    seen_t: set[str] = set()
                    picked: list[tuple[str, str]] = []
                    for cost, tac, src in sorted(cands, key=lambda x: x[0]):
                        tac = (tac or "").strip()
                        if (not tac or "\n" in tac or "?" in tac
                                or _FORBIDDEN_TAC_RE.search(tac)
                                or tac in seen_t):
                            continue
                        seen_t.add(tac)
                        picked.append((tac, src))
                        if len(picked) >= 8:
                            break
                    stmt = make_leaf_theorem(theorem_header, sketch, h)
                    if not picked or stmt is None:
                        tr("portfolio", id=h.id, n_candidates=len(picked),
                           committed=False, detail="no candidates / no stmt")
                        still_broken_p.append((h, err))
                        continue
                    cand_tac = "first | " + " | ".join(t for t, _ in picked)
                    # Standalone probe: does the combined candidate close
                    # THIS leaf on its own? Only then do we trust it.
                    try:
                        _pres = _pf(stmt, "  " + cand_tac.replace("\n", "\n  "))
                        _ok = bool(_pres.get("ok"))
                    except Exception:
                        _ok = False
                    if not _ok:
                        tr("portfolio", id=h.id, n_candidates=len(picked),
                           committed=False,
                           sources=sorted({s for _, s in picked}),
                           detail="probe did not close the leaf standalone")
                        still_broken_p.append((h, err))
                        continue
                    h.tactic = cand_tac
                    repaired_ids.append(h.id)
                    intact.append(h)
                    did_anything = True
                    tr("portfolio", id=h.id, n_candidates=len(picked),
                       committed=True,
                       sources=sorted({s for _, s in picked}),
                       tactic=h.tactic[:200])
                broken = still_broken_p

            # Pass 1.5-T — THEORY ABDUCTION (opt-in, abduce_mode=
            # "theory"): when any leaf is stuck, ALL broken leaves are
            # handed to the deferred assume→cover→gate→prove loop at
            # once (the covering set spans leaves). One attempt per
            # sketch; leaves it fixes leave `broken`, the rest fall
            # through to decomposition / sketch repair.
            _refresh_plan(has_attributable_errors=True, broken_pairs=broken,
                          closer_broken=closer_broken,
                          setup_broken=setup_broken,
                          theory_spent_now=theory_spent)
            if (_plan_ok(STAGE_THEORY_LEAF)
                    and abduce_lemmas and broken and abduce_mode == "theory"
                    and not theory_spent):
                stuck_any = (abduce_theory_trigger == "always") or any(
                    broken_streak.get(h.id, 0) >= 2
                    or "maximum number of heartbeats" in err
                    or "timeout" in err.lower()
                    for h, err in broken)
                if stuck_any:
                    theory_spent = True
                    fixed_ids = _recognize_then_abduce(sketch, broken)
                    if fixed_ids and _bonus_granted < _MAX_BONUS_ROUNDS:
                        # See REPAIR C: a commit changes the proof, so the
                        # state after it deserves an iteration.
                        _bonus_granted += 1
                        tr("repair_bonus_round",
                           reason="theory committed — one extra repair "
                                  "round granted",
                           fixed=sorted(fixed_ids))
                    if fixed_ids:
                        still_t: list[tuple[HaveNode, str]] = []
                        for h, err in broken:
                            if h.id in fixed_ids:
                                repaired_ids.append(h.id)
                                intact.append(h)
                                did_anything = True
                            else:
                                still_t.append((h, err))
                        broken = still_t

            # Pass 1.5-TC — THEORY ABDUCTION FOR A STUCK CLOSER: when no
            # leaf is broken but the closer keeps failing (the b5_bare_v2
            # shape — trivial leaves, all the mathematics in the closer),
            # the leaf-based trigger above never fires. Pose the closer's
            # obligation as a pseudo-leaf: original theorem goal with
            # every have in scope as a hypothesis. On commit, the
            # proposed CLOSER_ID tactic replaces the closer and the
            # invented lemmas are already spliced into the header.
            _refresh_plan(has_attributable_errors=True, broken_pairs=broken,
                          closer_broken=closer_broken,
                          setup_broken=setup_broken,
                          theory_spent_now=theory_spent)
            if (_plan_ok(STAGE_THEORY_CLOSER)
                    and abduce_lemmas and abduce_mode == "theory"
                    and not theory_spent and not broken and closer_broken
                    and probe_fn is not None):
                closer_err = "\n".join(errs.get(CLOSER_ID, []))
                closer_stuck = (
                    abduce_theory_trigger == "always"
                    or broken_streak.get(CLOSER_ID, 0) >= 2
                    or "maximum number of heartbeats" in closer_err
                    or "timeout" in closer_err.lower())
                parts_h = split_theorem_header(theorem_header)
                if closer_stuck and parts_h is not None:
                    theory_spent = True
                    pseudo = HaveNode(
                        CLOSER_ID, parts_h[1].strip(), sketch.closer,
                        [h.id for h in sketch.haves])
                    tr("abduce_theory", stage="closer-stuck trigger")
                    fixed_ids = _recognize_then_abduce(sketch, [(pseudo, closer_err)])
                    if CLOSER_ID in fixed_ids:
                        repaired_ids.append(CLOSER_ID)
                        closer_broken = False
                        did_anything = True
                        if _bonus_granted < _MAX_BONUS_ROUNDS:
                            _bonus_granted += 1
                            tr("repair_bonus_round",
                               reason="closer theory committed — one extra "
                                      "repair round granted")

            # Pass 1.5 — LEMMA ABDUCTION for stuck leaves (opt-in): a
            # leaf broken twice in a row, or dying on a certificate-
            # search timeout, gets one shot at invented helper lemmas
            # (kernel-gated) before we fall back to in-place
            # decomposition. Timeout errors trigger immediately: more
            # repair rounds cannot fix a simplex blow-up, but a lemma
            # that splits the search can.
            _refresh_plan(has_attributable_errors=True, broken_pairs=broken,
                          closer_broken=closer_broken,
                          setup_broken=setup_broken,
                          theory_spent_now=theory_spent)
            if (_plan_ok(STAGE_EAGER_ABDUCE)
                    and abduce_lemmas and broken and abduce_mode == "eager"):
                still_broken_a: list[tuple[HaveNode, str]] = []
                for h, err in broken:
                    stuck = (broken_streak.get(h.id, 0) >= 2
                             or "maximum number of heartbeats" in err
                             or "timeout" in err.lower())
                    if (stuck and abduce_spent.get(h.id, 0) < 1
                            and _abduce_leaf(sketch, h, err)):
                        abduce_spent[h.id] = 1
                        repaired_ids.append(h.id)
                        intact.append(h)
                        did_anything = True
                    else:
                        still_broken_a.append((h, err))
                broken = still_broken_a

            # Pass 2 — RECURSIVE DECOMPOSITION for stubborn leaves: a
            # leaf broken twice in a row already survived one ordinary
            # repair; a single-tactic fix is evidently not enough, so
            # decompose it into its own sub-DAG of `have`s.
            _refresh_plan(has_attributable_errors=True, broken_pairs=broken,
                          closer_broken=closer_broken,
                          setup_broken=setup_broken,
                          theory_spent_now=theory_spent)
            if _plan_ok(STAGE_DECOMPOSE) and decompose_depth > 0 and broken:
                still_broken2: list[tuple[HaveNode, str]] = []
                for h, err in broken:
                    if (broken_streak.get(h.id, 0) >= 2
                            and decompose_spent.get(h.id, 0) < decompose_depth
                            and _decompose_leaf(sketch, h)):
                        decompose_spent[h.id] = (
                            decompose_spent.get(h.id, 0) + 1)
                        decomposed.append(h.id)
                        repaired_ids.append(h.id)
                        intact.append(h)
                        did_anything = True
                    else:
                        still_broken2.append((h, err))
                broken = still_broken2

            # Pass 3 — sketch LLM repairs whatever the closer didn't
            # take: remaining leaves, the final closer, and/or the setup.
            _refresh_plan(has_attributable_errors=True, broken_pairs=broken,
                          closer_broken=closer_broken,
                          setup_broken=setup_broken,
                          theory_spent_now=theory_spent)
            if _plan_ok(STAGE_LLM_REPAIR) and (
                    broken or closer_broken or setup_broken):
                remaining_ids = {h.id for h, _ in broken}
                rep_user = repair_user_prompt(
                    theorem_header, broken, intact, sketch.closer,
                    closer_broken, "\n".join(errs.get(CLOSER_ID, [])),
                    premises=premises,
                    setup=sketch.setup,
                    setup_broken=setup_broken,
                    setup_error="\n".join(setup_errs or []),
                )
                try:
                    rep_raw = sketch_llm_call(REPAIR_SYSTEM, rep_user)
                except Exception as e:
                    tr("llm_error", detail=f"{type(e).__name__}: {e}")
                    return _final(sketch, body, "llm",
                                  f"{type(e).__name__}: {e}", attempt)
                raw_responses.append(rep_raw)
                if not rep_raw.strip():
                    # Provider returned nothing (even after the policy
                    # adapter's own empty-response retry). Another round
                    # with the identical prompt buys nothing.
                    repair_errors.append("empty_repair_response")
                    tr("repair_break", reason="empty_repair_response")
                    break
                if rep_raw == prev_repair_raw:
                    # Model is stuck emitting the same repair — verifying
                    # it again buys nothing. Outer retry instead.
                    tr("repair_break",
                       reason="identical repair response (model stuck) — "
                              "outer retry")
                    break
                prev_repair_raw = rep_raw
                applied, rep_err = _apply_repairs(
                    sketch, rep_raw, remaining_ids, closer_broken,
                    setup_broken,
                )
                if rep_err:
                    repair_errors.append(f"repair_not_applied: {rep_err}")
                    tr("repair_not_applied", reason=rep_err)
                else:
                    repaired_ids.extend(applied)
                    did_anything = True
                    tr("repair_applied", ids=applied)

            if not did_anything:
                tr("repair_break",
                   reason="no repair pass changed anything — outer retry "
                          "with feedback")
                break  # nothing repairable — outer retry with feedback
            total_repair_rounds += 1

        last_error = strip_warning_blocks(
            res.get("errors") or "")[:1500]
        if attempt == sketch_attempts:
            return _final(sketch, body, "verify", last_error, attempt)
    # Unreachable: loop always returns.
    return _final(None, None, "llm", "exhausted attempts", sketch_attempts)
