def error_lessons(errors: str) -> list[str]:
    """Lessons implied by a Lean error blob, as short imperatives.

    Used to give the theory loop a MEMORY of error classes across rounds
    and sketch attempts. Without it the same correction is relearned from
    scratch: putnam6_easy_v2 hit `dependsOnNoncomputable` three times
    (t=3826s, 5595s, 8325s), each time the next round added
    `noncomputable` and each new theory dropped it again — roughly 2,900s
    of probe compiles spent on one keyword. The revision ledger carried
    the error TEXT but nothing carried the CORRECTION forward.
    """
    if not errors:
        return []
    out: list[str] = []
    for pat, lesson in _ERROR_SIGNATURES:
        if re.search(pat, errors, re.I) and lesson not in out:
            out.append(lesson)
    return out


def theory_revise_prompt(prev_raw: str,
                         failures: list[tuple[str, str]],
                         stuck: list[tuple[str, str, str]],
                         premises: list[str] | None = None,
                         lessons: list[str] | None = None) -> str:
    """Feed the per-lemma status ledger back for a REVISED theory.

    The ledger lists EVERY lemma's fate (PROVED / PROOF FAILED /
    gate failure) — without it the model misdiagnoses which lemma
    survived and 'fixes' the wrong one (observed on arm_engel3_v2)."""
    parts = ["Your previous theory did not fully succeed. "
             "Previous response:",
             prev_raw[:3000],
             "\nStatus ledger (every lemma's actual fate — trust THIS, "
             "not your memory of what happened):"]
    for what, err in failures:
        parts.append(f"\n### {what}"
                     + (f"\n{err[:900]}" if err.strip() else ""))
    parts.append(
        "\nPropose a REVISED theory (STRICT JSON, same shape, "
        "statements only). Rules:\n"
        "  - It must still satisfy ALL the stuck leaves below.\n"
        "  - Include EVERY lemma the final theory needs — lemmas "
        "marked PROVED are cached and will NOT be re-proved, but they "
        "must appear in your `lemmas` list (verbatim statement) to be "
        "kept.\n"
        "  - For failed lemmas: reformulate, split into easier lemmas, "
        "generalize, or introduce new definitions; novelty is welcome "
        "as long as the criteria are met.")
    if lessons:
        parts.append(
            "\nERRORS THIS PROBLEM HAS ALREADY PAID FOR — every one cost a "
            "full compile. Do NOT reintroduce them:")
        parts += [f"  - {ls}" for ls in lessons]
    for lid, stmt, err in stuck:
        parts.append(f"\n### leaf `{lid}`\n{stmt} := by sorry")
    if premises:
        parts.append("\nRetrieved Mathlib names:\n"
                     + "\n".join(f"- {p}" for p in premises[:24]))
    return "\n".join(parts)


