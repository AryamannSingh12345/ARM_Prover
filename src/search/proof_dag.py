# ---------- Mathlib-pin renames ----------------------------------------------

# The model reliably emits pre-rename Mathlib names regardless of what
# the prompt says — `Unknown identifier `div_le_div_iff`` sank four
# engel3/leaf06 runs even with the current `₀` names spliced into the
# premises. In the pinned Mathlib these lemmas were renamed with a `₀`
# suffix (same signatures, so the rename is argument-compatible) and
# the old names are gone. Every LLM response is rewritten BEFORE
# parsing; the verifier still sees exactly what gets committed.
_PIN_RENAMES = (
    "div_le_div_iff", "div_lt_div_iff", "le_div_iff", "div_le_iff",
    "lt_div_iff", "div_lt_iff",
)
_PIN_RENAME_RE = re.compile(
    r"\b(" + "|".join(sorted(_PIN_RENAMES, key=len, reverse=True))
    + r")\b(?!₀)")


# Big-operator binder syntax. Mathlib changed `∑ x in s, f x` to
# `∑ x ∈ s, f x`; the old form is a hard PARSE error in the pin
# ("unexpected token 'in'; expected ','"). Models emit the old spelling
# constantly — it was correct for most of their training data — and a
# parse error costs a full compile while telling us nothing about the
# mathematics. On putnam_2020_a2_v2 this consumed the ENTIRE budget of
# `aux_weighted_choose_to_lower`, the only hard lemma in the problem:
# three attempts, 824s + 749s + 547s = 2,120s of Lean, and its Pascal
# argument was never once evaluated.
#
# Same class as the `₀` renames above — a pin-version drift, uniform,
# environment-derived, carrying no problem knowledge.
#
# The binder segment cannot cross `,` `∈` or a newline, so an
# already-correct `∑ x ∈ s, …` is untouched and only the binder's own
# `in` is rewritten (a term like `interval` is safe: `\bin\b`).
_BIGOP_IN_RE = re.compile(r"([∑∏⨆⨅⋃⋂][^,∈\n]*?)\bin\b")


def apply_pin_renames(text: str) -> str:
    """Rewrite text to the pinned Mathlib's spelling.

    Two version drifts, both applied to every LLM response before
    parsing; the verifier still sees exactly what gets committed.

    1. Stale (pre-`₀`-rename) identifiers. Word-boundary safe:
       `div_le_div_iff_left` is untouched, an already-correct
       `div_le_div_iff₀` is not double-suffixed, and primed forms
       (`div_le_iff'` → `div_le_iff₀'`) map to the primed `₀` variants.
    2. Big-operator binders: `∑ x in s,` → `∑ x ∈ s,`.
    """
    text = _PIN_RENAME_RE.sub(lambda m: m.group(1) + "₀", text)
    return _BIGOP_IN_RE.sub(lambda m: m.group(1) + "∈", text)


# ---------- invented-lemma library -------------------------------------------

_DECL_NAME_RE = re.compile(
    r"^\s*(?:private\s+)?(?:noncomputable\s+)?"
    r"(?:lemma|theorem|def|abbrev)\s+([A-Za-z_][A-Za-z0-9_'.₀-₉]*)",
    re.M,
)


def _append_lemma_library(path: str, tag: str, decls: list[str],
                          *, provenance: dict | None = None) -> None:
    """Append newly invented declarations to the on-disk lemma library,
    skipping any whose declared name is already in the file (the bank
    accumulates across runs; blind appends produced duplicate
    `aux_titu3` declarations that poison any header the file is spliced
    into). The library is telemetry, never load-bearing — all failures
    are swallowed.

    Also writes a provenance record per declaration to the JSONL sidecar
    (`<path>.jsonl`) via `search.lemma_bank` — statement hash, source
    problem/split, run id, model, mathlib commit and a UTC timestamp, so
    a clean evaluation can later filter the bank by split and chronology
    (`allowed_for_eval` defaults False). The sidecar dedups by statement
    hash (semantic) rather than by name. `provenance` may be None (older
    callers / tests): the .lean append is unchanged and the sidecar
    records carry null run/problem fields."""
    try:
        from pathlib import Path as _P
        p = _P(path)
        existing: set[str] = set()
        if p.exists():
            existing = set(_DECL_NAME_RE.findall(
                p.read_text(encoding="utf-8", errors="replace")))
        fresh: list[str] = []
        for d in decls:
            m = _DECL_NAME_RE.match(d)
            name = m.group(1) if m else None
            if name is not None and name in existing:
                continue
            fresh.append(d)
            if name is not None:
                existing.add(name)
        if fresh:
            with p.open("a", encoding="utf-8") as fh:
                fh.write(f"\n-- {tag}\n" + "\n\n".join(fresh) + "\n")
    except Exception:
        pass
    # Provenance sidecar — separate try/except so a sidecar failure never
    # disturbs the (equally best-effort) .lean append above.
    try:
        from search import lemma_bank
        records = lemma_bank.build_records(
            decls, tag=tag, provenance=provenance)
        lemma_bank.append_records(lemma_bank.sidecar_path(path), records)
    except Exception:
        pass


