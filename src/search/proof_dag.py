# ---------- JSON parsing -----------------------------------------------------

_FENCE_RE   = re.compile(r"^```(?:json)?\s*", re.MULTILINE)
_FENCE_END  = re.compile(r"```\s*$", re.MULTILINE)


def _strip_fences(text: str) -> str:
    s = text.strip()
    s = _FENCE_RE.sub("", s)
    s = _FENCE_END.sub("", s)
    return s.strip()


def _extract_json_object(text: str) -> dict | None:
    """Find the first balanced {...} block and json-parse it. Tolerant of
    LLMs that wrap the JSON in commentary or fences."""
    if not text:
        return None
    s = _strip_fences(text)
    # First try direct parse.
    try:
        return json.loads(s)
    except Exception:
        pass
    # Find the outermost {...}.
    depth = 0
    start = -1
    for i, ch in enumerate(s):
        if ch == "{":
            if depth == 0:
                start = i
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0 and start >= 0:
                blob = s[start:i + 1]
                try:
                    return json.loads(blob)
                except Exception:
                    continue
    return None


def parse_sketch(raw: str) -> tuple[Sketch | None, str | None]:
    """Returns (sketch, error_or_None)."""
    obj = _extract_json_object(raw)
    if obj is None:
        return None, "no_json_object_found"
    if not isinstance(obj, dict):
        return None, "json_not_object"
    haves_raw = obj.get("haves", [])
    closer = obj.get("closer", "")
    if not isinstance(haves_raw, list):
        return None, "haves_not_list"
    if not isinstance(closer, str) or not closer.strip():
        return None, "closer_missing_or_empty"
    haves: list[HaveNode] = []
    for i, h in enumerate(haves_raw):
        if not isinstance(h, dict):
            return None, f"have_{i}_not_object"
        hid = h.get("id")
        htype = h.get("type")
        htac = h.get("tactic")
        hdeps = h.get("depends", []) or []
        if not isinstance(hid, str) or not hid.strip():
            return None, f"have_{i}_missing_id"
        if not isinstance(htype, str) or not htype.strip():
            return None, f"have_{i}_missing_type"
        if not isinstance(htac, str) or not htac.strip():
            return None, f"have_{i}_missing_tactic"
        if not isinstance(hdeps, list):
            return None, f"have_{i}_depends_not_list"
        deps_clean = [str(d) for d in hdeps if isinstance(d, str)]
        haves.append(HaveNode(
            id=hid.strip(),
            type_text=htype.strip(),
            tactic=htac.strip(),
            depends=deps_clean,
        ))
    # Reject duplicate ids.
    if len({h.id for h in haves}) != len(haves):
        return None, "duplicate_have_ids"
    # Optional setup block: tactic lines executed before the haves.
    setup_raw = obj.get("setup", []) or []
    if not isinstance(setup_raw, list):
        return None, "setup_not_list"
    setup = [str(s).strip() for s in setup_raw
             if isinstance(s, str) and s.strip()]
    # Reject sketches containing forbidden cheat tactics. Faster than
    # waiting for verify_proof to flag used_sorry / used_native_decide.
    if _FORBIDDEN_TAC_RE.search(closer):
        return None, "closer_uses_forbidden_tactic"
    for s in setup:
        if _FORBIDDEN_TAC_RE.search(s):
            return None, "setup_uses_forbidden_tactic"
    for h in haves:
        if _FORBIDDEN_TAC_RE.search(h.tactic):
            return None, f"have_{h.id}_uses_forbidden_tactic"
    return Sketch(haves=haves, closer=closer.strip(), raw_response=raw,
                  setup=setup), None


def topo_sort(haves: list[HaveNode]) -> tuple[list[HaveNode] | None, str | None]:
    """Return (sorted_haves, error). Cycles → None + cycle error.

    `depends` entries that aren't have ids are DROPPED, not rejected:
    models routinely list the theorem's own hypotheses (h₀, h₁, …) as
    dependencies. Those are always in scope, so they carry no ordering
    constraint — only inter-have edges matter here. (Observed failure
    mode: 14-leaf sketches discarded three times over for depending on
    h₀.)"""
    by_id = {h.id: h for h in haves}
    for h in haves:
        h.depends = [d for d in h.depends if d in by_id]
    # Kahn's algorithm.
    indeg: dict[str, int] = {h.id: 0 for h in haves}
    children: dict[str, list[str]] = {h.id: [] for h in haves}
    for h in haves:
        for d in h.depends:
            indeg[h.id] += 1
            children[d].append(h.id)
    queue = [hid for hid, d in indeg.items() if d == 0]
    out: list[HaveNode] = []
    while queue:
        hid = queue.pop(0)
        out.append(by_id[hid])
        for c in children[hid]:
            indeg[c] -= 1
            if indeg[c] == 0:
                queue.append(c)
    if len(out) != len(haves):
        return None, "cycle_in_have_graph"
    return out, None


