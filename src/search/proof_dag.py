def repair_user_prompt(
    theorem_header: str,
    broken: list[tuple["HaveNode", str]],
    intact: list["HaveNode"],
    closer: str,
    closer_broken: bool,
    closer_error: str,
    premises: list[str] | None = None,
    setup: list[str] | None = None,
    setup_broken: bool = False,
    setup_error: str = "",
) -> str:
    parts = [f"Theorem being proved:\n\n{theorem_header} := by ...\n"]
    if premises:
        parts.append(_premise_block(premises).rstrip())
        parts.append("")
    if intact:
        parts.append("Verified steps ALREADY IN SCOPE (do not change):")
        for h in intact:
            parts.append(f"  {h.id} : {h.type_text}")
        parts.append("")
    if setup_broken:
        parts.append("BROKEN setup block (tactic lines that run before "
                     "the first have — reply with a full replacement "
                     'list in "setup"):')
        for ln in (setup or []):
            parts.append(f"  {ln}")
        parts.append(f"  Lean error: {setup_error[:600]}")
        parts.append("")
    if broken:
        parts.append("BROKEN steps (fix each):")
        for h, err in broken:
            parts.append(f"  id: {h.id}")
            parts.append(f"  claimed type: {h.type_text}")
            parts.append(f"  failed tactic: {h.tactic}")
            parts.append(f"  Lean error: {err[:600]}")
            parts.append("")
    if closer_broken:
        parts.append(f"BROKEN closer:\n  {closer}")
        parts.append(f"  Lean error: {closer_error[:600]}\n")
    parts.append(_REPAIR_SHAPE)
    return "\n".join(parts)


# ---------- leaf-closer support ----------------------------------------------
# A specialized whole-proof prover (Goedel-Prover-class) can close broken
# leaves during repair: each leaf is posed as a standalone theorem whose
# hypotheses are the ORIGINAL theorem's binders plus the leaf's `depends`
# haves. The prover's candidates are combined into a `first | …` so one
# assembled-proof compile tests them all — no per-leaf Lean invocation.

_HEADER_OPEN = "([{⦃⟨"
_HEADER_CLOSE = ")]}⦄⟩"
# Multiline: headers may carry `open … in` prefix lines before the
# `theorem` keyword (prepend_open_scopes), so anchor per-line.
_THEOREM_NAME_RE = re.compile(r"^(theorem|lemma)\s+\S+", re.M)


# Start of the FINAL declaration inside a (possibly prelude-carrying)
# header. The prelude (abbrevs, opens, variables…) contains top-level
# colons of its own, so the binder/goal split below must scan only from
# the declaration onward.
_LAST_DECL_RE = re.compile(
    r"(?m)^[ \t]*(?:@\[[^\]]*\][ \t\r\n]*)*"
    r"(?:noncomputable[ \t]+|private[ \t]+|protected[ \t]+)*"
    r"(?:theorem|lemma|def|abbrev|instance|example)\b")


def _decl_offset(header: str) -> int:
    """Offset of the final declaration keyword; 0 when none found
    (bare-header behaviour, identical to the pre-prelude era)."""
    last = 0
    for m in _LAST_DECL_RE.finditer(header):
        last = m.start()
    return last


def split_theorem_header(header: str) -> tuple[str, str] | None:
    """Split `[prelude] theorem name <binders> : <goal>` at the first
    TOP-LEVEL colon OF THE FINAL DECLARATION (colons inside binder
    brackets — and anywhere in the prelude — don't count). Returns
    (prefix_without_colon, goal); the prefix keeps the prelude so leaf
    statements built from it still see abbrevs/opens."""
    depth = 0
    off = _decl_offset(header)
    for i in range(off, len(header)):
        ch = header[i]
        if ch in _HEADER_OPEN:
            depth += 1
        elif ch in _HEADER_CLOSE:
            depth = max(0, depth - 1)
        elif ch == ":" and depth == 0 and header[i:i + 2] != ":=":
            return header[:i].rstrip(), header[i + 1:].strip()
    return None


def make_leaf_theorem(theorem_header: str, sketch: Sketch,
                      leaf: HaveNode) -> str | None:
    """Standalone theorem statement for one leaf: original binders +
    the leaf's dependency haves as named hypotheses, goal = leaf type.
    Prompt-only — never compiled on its own."""
    parts = split_theorem_header(theorem_header)
    if parts is None:
        return None
    prefix, _goal = parts
    # Rename the FINAL declaration (any kind) to a leaf theorem; the
    # prelude before it is preserved untouched.
    off = _decl_offset(prefix)
    renamed = re.sub(
        r"^[ \t]*(?:@\[[^\]]*\][ \t\r\n]*)*"
        r"(?:noncomputable[ \t]+|private[ \t]+|protected[ \t]+)*"
        r"(?:theorem|lemma|def|abbrev|instance|example)(\s+\S+)?",
        f"theorem leaf_{leaf.id}",
        prefix[off:], count=1)
    prefix = prefix[:off] + renamed
    by_id = {h.id: h for h in sketch.haves}
    dep_binders = "".join(
        f" ({by_id[d].id} : {by_id[d].type_text})"
        for d in leaf.depends if d in by_id
    )
    return f"{prefix}{dep_binders} : {leaf.type_text}"


