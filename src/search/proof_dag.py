def _premise_block(premises: list[str] | None) -> str:
    """Retrieved-lemma block spliced into prompts. Invented lemma names
    are the dominant hard-problem failure mode (amc12_2001_p5 fabricated
    `Nat.factorial_eq_mul_doubleFactorial`); grounding the model in real
    declaration names converts 'guess the name' into 'pick from a list'."""
    if not premises:
        return ""
    listing = "\n".join(f"  {p}" for p in premises)
    return (
        "Mathlib declarations retrieved for this theorem (REAL names — "
        "when you need a library lemma, prefer one of these over a "
        "name from memory):\n"
        f"{listing}\n\n"
    )


