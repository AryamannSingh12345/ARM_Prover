# ---------- spurious-intro repair -------------------------------------------
#
# MEASURED on p1963a2_dag_v2 (2026-08-18). In closer-stuck mode the
# closer's obligation is posed to the model as a STANDALONE goal, so the
# model reasonably opens its tactic by introducing the goal's binders
# (`intro m hm`). But at the splice point the sketch's own `setup` has
# ALREADY introduced them, so Lean reports:
#
#   Tactic `introN` failed: There are no additional binders or `let`
#   bindings in the goal to introduce
#
# This killed theory rounds 0 AND 4 of that run — and round 4 was the
# GOOD theory (the elementary gap-persistence / dyadic-fixed-point
# decomposition, after the over-general `rpow` classification had been
# abandoned). A correct decomposition was lost to a context mismatch in
# the harness, not to mathematics.
#
# The fix is ERROR-DRIVEN, never speculative: nothing is stripped until
# the kernel has actually reported this diagnostic against the closer.
# A closer whose leading `intro` is legitimate never matches, so a
# working tactic cannot be broken.
# Quoting is deliberately permissive. The implicit-`sorry` check in
# compile_verify.py was DEAD CODE for months because it expected
# 'sorry' while this toolchain emits `sorry` — do not repeat that here
# by pinning one quote style.
_INTRO_NO_BINDERS_RE = re.compile(
    r"[`'\"]?intro(?:N)?[`'\"]? failed.{0,80}?no additional binders",
    re.I | re.S)

_LEADING_INTRO_RE = re.compile(r"^\s*intros?\b[^\n]*$", re.M)


def strip_leading_intro(tactic: str) -> str | None:
    """Drop the leading `intro …` / `intros …` line of a tactic block.

    Returns the rewritten block, or None when the first meaningful line
    is not an intro (nothing to repair). Only the FIRST line is
    considered: a later `intro` is inside a bullet or a nested `have`
    and belongs to a different goal.
    """
    lines = tactic.split("\n")
    for i, ln in enumerate(lines):
        if not ln.strip():
            continue
        if not _LEADING_INTRO_RE.match(ln):
            return None
        rest = [x for j, x in enumerate(lines) if j != i]
        # An intro-only tactic would become empty, which is a parse
        # error rather than a repair.
        if not any(x.strip() for x in rest):
            return None
        return "\n".join(rest).strip("\n")
    return None


def tactic_cites(tactic: str, names: Iterable[str]) -> bool:
    """Does `tactic` reference any of `names` as a whole identifier?

    Used by the partial-commit path: a leaf tactic that names a lemma
    the kernel never accepted cannot be part of a partial commit, and
    probing it wastes a full compile on an `unknown identifier` error
    that says nothing about sufficiency.
    """
    for n in names:
        if not n:
            continue
        if re.search(r"(?<![\w.'])" + re.escape(n) + r"(?![\w.'])", tactic):
            return True
    return False


